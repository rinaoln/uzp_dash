"""Данные страницы — не открытым текстом.

ЭТО НЕ ШИФРОВАНИЕ, и выдавать это за шифрование нельзя. Ключ лежит в том же
файле, рядом с данными: любой, кто откроет консоль браузера, прочитает всё за
полминуты. Задача ровно одна — чтобы массивы отчёта не читались глазами, когда
файл открывают в блокноте или другом текстовом редакторе. От человека с умыслом
это не защищает и защищать не может; защита данных остаётся на том, кому файл
отдали.

ЧТО ПРЯЧЕТСЯ, А ЧТО НЕТ. Прячутся массивы — то, что на экран само не выводится:
детализация для выгрузок в Excel, подложки ячеек матрицы, полный список
организаций интерактивной таблицы. Сама вёрстка отчёта остаётся текстом: всё,
что видно на экране, в блокноте тоже видно, и сделать иначе нельзя, не
переписав страницу так, чтобы без JS она была пустой.

КАК СДЕЛАНО. Сдвиг кодов символов по двум замкнутым полосам:

  * печатная латиница и знаки, коды 32..126 без «<» — 94 позиции;
  * кириллица, коды 1024..1119 (Ё, А-я, ё) — 96 позиций.

Полосы замкнуты сами на себя, поэтому кодирование НЕ МЕНЯЕТ РАЗМЕР ФАЙЛА: один
байт остаётся одним, два — двумя. Base64 раздул бы отчёт примерно на треть
объёма данных, а его недавно специально уменьшали.

«<» из полосы исключён, а во входном JSON заменён на «\\u003c» — поэтому в
закодированном тексте этого символа нет вовсе. Благодаря этому текст кладётся
прямо внутрь <script> как есть: оборвать его последовательностью «</script» или
подменить сущностью «&…;» нечем, и экранировать ничего не нужно.
"""
from __future__ import annotations

import json
import math

# Ключ по умолчанию. Диапазон 1..93 — он же предел обратного сдвига в скрипте
# (см. `+94` и `+96` в DECODER: при большем ключе остаток ушёл бы в минус).
KEY = 37
_KEYS = tuple(range(1, 94))


def _shift(text: str, key: int) -> str:
    out = []
    for ch in text:
        c = ord(ch)
        if 32 <= c <= 126 and c != 60:
            j = (c - 32 if c < 60 else c - 33)
            j = (j + key) % 94
            out.append(chr(j + 32 if j < 28 else j + 33))
        elif 1024 <= c <= 1119:
            out.append(chr(1024 + (c - 1024 + key) % 96))
        else:
            out.append(ch)
    return "".join(out)


def _pick(text: str) -> tuple[str, int]:
    """Сдвинуть так, чтобы по готовому документу не прошлась чистка слова «ИНН».

    `html.sanitize` чистит ГОТОВЫЙ документ и меняет «ИНН» на «Орг.» — три
    символа на четыре. Сдвиг кириллицы в принципе может сложить «инн» из других
    букв, и тогда чистка молча испортит массив. Поэтому результат проверяется
    тем же выражением, и при совпадении берётся следующий ключ: полос замкнутых,
    ключей девяносто три, какой-нибудь подойдёт всегда.
    """
    # Импорт внутри функции намеренно: `html` подключает отсюда DECODER, и
    # импорт `html` на уровне модуля замкнул бы круг — к моменту разбора `veil`
    # выражение в `html` ещё не создано.
    from .html import _INN_WORD

    for key in (KEY, *(k for k in _KEYS if k != KEY)):
        enc = _shift(text, key)
        if not _INN_WORD.search(enc):
            return enc, key
    raise RuntimeError("не нашёлся ключ без слова «ИНН» в результате")


def _finite(o, n: list):
    """Заменить NaN и бесконечности на None во вложенных словарях и списках."""
    if isinstance(o, float) and not math.isfinite(o):
        n[0] += 1
        return None
    if isinstance(o, dict):
        return {k: _finite(v, n) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_finite(v, n) for v in o]
    return o


def hide(obj, slot: str) -> tuple[str, str]:
    """Массив — в документ закодированным. Отдаёт разметку и выражение для JS.

    `slot` — свой у каждого массива: он становится id элемента-хранилища, и по
    нему же скрипт его находит. Внутри одного файла тринадцать уровней отчёта,
    поэтому в `slot` всегда входит номер уровня.

    Хранилище ставится ПЕРЕД скриптом, который его читает: браузер исполняет
    инлайн-скрипты по ходу разбора документа, и элемент к этому моменту должен
    быть уже разобран.
    """
    # NaN и бесконечность в JSON недопустимы: Python их пишет, а JSON.parse в
    # браузере на них падает и не отдаёт массив ЦЕЛИКОМ — одно пустое число в
    # одной строке оставляло пустой всю таблицу. Поэтому сначала строгая запись;
    # если она не прошла, такие значения становятся null, а в лог сборки уходит,
    # в каком массиве и сколько их было, — иначе источник так и остался бы
    # незамеченным.
    try:
        text = json.dumps(obj, ensure_ascii=False, allow_nan=False)
    except ValueError:
        n = [0]
        obj = _finite(obj, n)
        text = json.dumps(obj, ensure_ascii=False, allow_nan=False)
        from .. import progress
        progress.warn(f"В массиве «{slot}» было {n[0]} пустых чисел (NaN) — "
                      f"записаны как пустые значения, иначе браузер не открыл бы "
                      f"таблицу. Источник стоит найти: число где-то не посчиталось")
    text = text.replace("<", "\\u003c")
    enc, key = _pick(text)
    holder = f'<script type="application/octet-stream" id="{slot}">{enc}</script>'
    return holder, f'__vd("{slot}",{key})'


# Обратный сдвиг. Собирается кусками по 4096 кодов: `String.fromCharCode.apply`
# с сотней тысяч аргументов упирается в предел длины списка аргументов и падает.
DECODER = """<script>
window.__vd=function(id,k){
  var s=document.getElementById(id).textContent,o=[],i,c,j;
  for(i=0;i<s.length;i++){
    c=s.charCodeAt(i);
    if(c>=32&&c<=126&&c!==60){j=((c<60?c-32:c-33)-k+94)%94;o.push(j<28?j+32:j+33);}
    else if(c>=1024&&c<=1119){o.push(1024+((c-1024-k+96)%96));}
    else o.push(c);
  }
  var t='',n,F=String.fromCharCode;
  for(n=0;n<o.length;n+=4096)t+=F.apply(null,o.slice(n,n+4096));
  return JSON.parse(t);
};
</script>"""


class Hidden:
    """Подписи, которых не должно быть в разметке открытым текстом.

    ЗАЧЕМ ОТДЕЛЬНО ОТ `hide`. `hide` прячет массивы — то, что на экран само не
    выводится. Здесь наоборот: текст НУЖНО показать, и спрятать его от
    текстового редактора можно единственным способом — не писать в разметку
    вовсе, а подставить скриптом из того же закодированного массива.

    Так уезжает подпись организации. После замены имён людей на номер (см.
    `anonymize.org_label`) в вёрстке осталось четыре с половиной сотни строк
    вида «Орг. 1000134503» — номер клиента открытым текстом в каждой.

    ЧТО ЭТО МЕНЯЕТ, А ЧТО НЕТ. На экране всё как было. В блокноте вместо
    подписи пустой элемент. Без скрипта подписи не будет вовсе — поэтому сюда
    идёт только то, что и так рисуется скриптом или рядом с ним; разметка,
    которая обязана работать без JS, остаётся как есть.

    Словарь общий на документ и с дедупликацией: одна и та же организация
    встречается на нескольких уровнях отчёта, и хранить её подпись тринадцать
    раз незачем.
    """

    def __init__(self, slot: str = "d-text"):
        self.slot = slot
        self._list: list[str] = []
        self._idx: dict[str, int] = {}

    def clear(self) -> None:
        """В одном процессе отчёт собирают дважды — остатки прошлой не нужны."""
        self._list.clear()
        self._idx.clear()

    def _n(self, text: str) -> int:
        if text not in self._idx:
            self._idx[text] = len(self._list)
            self._list.append(text)
        return self._idx[text]

    def text(self, value) -> str:
        """Подпись → пустой элемент-место. Заполнится скриптом."""
        s = str(value or "").strip()
        if not s:
            return ""
        return f'<span class="vx" data-v="{self._n(s)}"></span>'

    def title(self, value) -> str:
        """Подсказка → атрибут для подстановки в title. Готовый кусок атрибутов."""
        s = str(value or "").strip()
        if not s:
            return ""
        return f' data-vt="{self._n(s)}"'

    def script(self) -> str:
        """Хранилище и заполнение. Ставится ПОСЛЕ всей размеченной подписи.

        Заполнение идёт синхронно, по ходу разбора документа, а не по
        DOMContentLoaded: отчёт до готовности раскладки закрыт маской, и подписи
        должны встать под ней, а не появиться на глазах у читателя.
        """
        if not self._list:
            return ""
        holder, expr = hide(self._list, self.slot)
        return (holder + "<script>(function(){var D=" + expr + ",i,e;"
                "var a=document.querySelectorAll('.vx');"
                "for(i=0;i<a.length;i++){e=a[i];e.textContent=D[+e.getAttribute('data-v')];}"
                "var b=document.querySelectorAll('[data-vt]');"
                "for(i=0;i<b.length;i++){e=b[i];e.title=D[+e.getAttribute('data-vt')];}"
                "})();</script>")
