"""Данные страницы — не открытым текстом.

ЭТО НЕ ШИФРОВАНИЕ, и выдавать это за шифрование нельзя. Ключ лежит в том же
файле, рядом с данными: любой, кто откроет консоль браузера, прочитает всё за
полминуты. Задача ровно одна — чтобы массивы отчёта не читались глазами, когда
файл открывают в блокноте или другом текстовом редакторе. От человека с умыслом
это не защищает и защищать не может; защита данных остаётся на том, кому файл
отдали.

ЧТО ПРЯЧЕТСЯ, А ЧТО НЕТ. Прячутся массивы — то, что на экран само не выводится:
детализация для выгрузок в Excel, подложки ячеек матрицы, полный список
организаций интерактивной таблицы. Сама вёрстка отчёта остаётся текстом: всё,
что видно на экране, в блокноте тоже видно, и сделать иначе нельзя, не
переписав страницу так, чтобы без JS она была пустой.

КАК СДЕЛАНО. Сдвиг кодов символов по двум замкнутым полосам:

  * печатная латиница и знаки, коды 32..126 без «<» — 94 позиции;
  * кириллица, коды 1024..1119 (Ё, А-я, ё) — 96 позиций.

Полосы замкнуты сами на себя, поэтому кодирование НЕ МЕНЯЕТ РАЗМЕР ФАЙЛА: один
байт остаётся одним, два — двумя. Base64 раздул бы отчёт примерно на треть
объёма данных, а его недавно специально уменьшали.

«<» из полосы исключён, а во входном JSON заменён на «\\u003c» — поэтому в
закодированном тексте этого символа нет вовсе. Благодаря этому текст кладётся
прямо внутрь <script> как есть: оборвать его последовательностью «</script» или
подменить сущностью «&…;» нечем, и экранировать ничего не нужно.
"""
from __future__ import annotations

import json

# Ключ по умолчанию. Диапазон 1..93 — он же предел обратного сдвига в скрипте
# (см. `+94` и `+96` в DECODER: при большем ключе остаток ушёл бы в минус).
KEY = 37
_KEYS = tuple(range(1, 94))


def _shift(text: str, key: int) -> str:
    out = []
    for ch in text:
        c = ord(ch)
        if 32 <= c <= 126 and c != 60:
            j = (c - 32 if c < 60 else c - 33)
            j = (j + key) % 94
            out.append(chr(j + 32 if j < 28 else j + 33))
        elif 1024 <= c <= 1119:
            out.append(chr(1024 + (c - 1024 + key) % 96))
        else:
            out.append(ch)
    return "".join(out)


def _pick(text: str) -> tuple[str, int]:
    """Сдвинуть так, чтобы по готовому документу не прошлась чистка слова «ИНН».

    `html.sanitize` чистит ГОТОВЫЙ документ и меняет «ИНН» на «Орг.» — три
    символа на четыре. Сдвиг кириллицы в принципе может сложить «инн» из других
    букв, и тогда чистка молча испортит массив. Поэтому результат проверяется
    тем же выражением, и при совпадении берётся следующий ключ: полос замкнутых,
    ключей девяносто три, какой-нибудь подойдёт всегда.
    """
    # Импорт внутри функции намеренно: `html` подключает отсюда DECODER, и
    # импорт `html` на уровне модуля замкнул бы круг — к моменту разбора `veil`
    # выражение в `html` ещё не создано.
    from .html import _INN_WORD

    for key in (KEY, *(k for k in _KEYS if k != KEY)):
        enc = _shift(text, key)
        if not _INN_WORD.search(enc):
            return enc, key
    raise RuntimeError("не нашёлся ключ без слова «ИНН» в результате")


def hide(obj, slot: str) -> tuple[str, str]:
    """Массив — в документ закодированным. Отдаёт разметку и выражение для JS.

    `slot` — свой у каждого массива: он становится id элемента-хранилища, и по
    нему же скрипт его находит. Внутри одного файла тринадцать уровней отчёта,
    поэтому в `slot` всегда входит номер уровня.

    Хранилище ставится ПЕРЕД скриптом, который его читает: браузер исполняет
    инлайн-скрипты по ходу разбора документа, и элемент к этому моменту должен
    быть уже разобран.
    """
    text = json.dumps(obj, ensure_ascii=False).replace("<", "\\u003c")
    enc, key = _pick(text)
    holder = f'<script type="application/octet-stream" id="{slot}">{enc}</script>'
    return holder, f'__vd("{slot}",{key})'


