def _hero(a: analyze.Analysis, idx: int, titles: dict) -> str:
    """Вердикт по ПРОГНОЗУ текущего месяца. Закрытый месяц — строкой ниже:
    это единственная твёрдая цифра, и по ней же считается ранг ТБ."""
    r = a.verdict["rcp"]
    d = a.dates or {}
    st = C.status_of(r["exec"])
    word = {"good": "План выполняется", "warn": "План близок к выполнению",
            "bad": "План не выполняется"}[st]
    # сами цифры закрытого месяца живут в KPI-карточках ниже (по каждой метрике),
    # здесь остаётся только ранг: он один на ТБ и к отдельной метрике не привязан.
    # У банка ранга нет — сравнивать не с кем, и строка про него не пишется вовсе.
    closed_txt = (f'закрытый месяц {C.esc(d.get("closed_label", ""))}' if not r["rank"]
                  else f'ранг ТБ {r["rank"]}/{r["n_tb"]} за закрытый месяц '
                       f'{C.esc(d.get("closed_label", ""))}')
    # процент отвечает «насколько», абсолют — «сколько людей». Без второго числа
    # 91% у банка и 91% у небольшого ГОСБ читаются как одна и та же новость
    fot = a.verdict["fot"]
    inner = (
        f'<div class="eyebrow">Прогноз выполнения на {C.esc(d.get("label", ""))}</div>'
        # Вердикт — только словом: процент выполнения относится к получателям, и в
        # заголовке плашки читался как общий по ней. Он стоит в своей строке
        # показателя, рядом с числами, из которых посчитан.
        f'<div class="verdict">{C.esc(word)}</div>'
        # Обе главные строки плашки — получатели и ФОТ — устроены одинаково:
        # прогноз → план → выполнение → отклонение, и несут класс row2-fot (крупное
        # начертание строки показателя). Класс проставлен в разметке, а не оставлен
        # на ux.js: скрипт вешает его на ПЕРВУЮ строку .row2 плашки, считая её
        # строкой ФОТ (в макете она стояла первой). У нас первая — получатели, и
        # ФОТ, равный ей по смыслу, оставался мелкой подписью.
        f'<div class="row2 row2-fot">Получатели: прогноз '
        f'<b>{C.fmt_num(r["fact"])}</b> '
        f'при плане {C.fmt_num(r["plan"])} · '
        f'<b style="color:{_col(r["exec"])}">{_pct(r["exec"])}</b> · '
        f'{_delta_html(r["fact"] - r["plan"], "чел")}'
        f'{_wow_chip(a, "rcp", "чел")}</div>'
        # Бейджа про разрыв до плана здесь нет: gap_rcp — это ровно план минус
        # прогноз, то же число и с тем же знаком уже стоит в строке выше.
        + C.meter(r["exec"])
        + f'<div class="row2 row2-fot">ФОТ: прогноз '
          f'<b>{C.fmt_num(fot["fact"] / 1e6)} млн ₽</b> '
          f'при плане {C.fmt_num(fot["plan"] / 1e6)} млн ₽ · '
        # процент набран как остальные числа строки и окрашен по статусу — так же, как
        # выполнение показано в карточках показателей ниже
          f'<b style="color:{_col(fot["exec"])}">{_pct(fot["exec"])}</b> · '
          f'{_delta_html((fot["fact"] - fot["plan"]) / 1e6, "млн ₽")}'
          f'{_wow_chip(a, "fot", "млн ₽", scale=1e6, digits=1, eps=0.05)}</div>'
        + f'<div class="row2">{closed_txt}</div>'
        + _wow_row(a)
        # сводка стоит ВНУТРИ плашки прогноза: это первый экран уровня, и
        # ответ на «что происходит с портфелем» должен быть виден без прокрутки
        + _exec_summary(a, idx, titles)
    )
    return C.card(inner, cls="hero")


# ДИНАМИКА НЕДЕЛЯ К НЕДЕЛЕ ПОКАЗЫВАЕТСЯ, ТОЛЬКО ЕСЛИ ЕСТЬ ЧТО ПОКАЗАТЬ.
#
# Раньше при нулевой дельте строка писала «без изменений», а при отсутствии базы —
# что сравнивать не с чем. Читателю от обеих формулировок пользы нет: строка
# занимает место в самой заметной плашке отчёта и выглядит как неработающий
# показатель. Правило теперь простое: нет цифры — нет и строки. Поэтому
# `_wow_num`/`_wow_pp` возвращают пустую строку на нулевой дельте, а строка
# целиком не рисуется, если ни одно из её чисел не заполнилось.
def _wow_num(delta: float, unit: str = "", digits: int = 0,
             eps: float = 0.5) -> str:
    """Изменение величины к прошлой сборке: знак, цвет, единица.

    Ноль в пределах округления — пусто: «+0 чел» читалось бы как настоящее
    изменение на ноль, а «без изменений» — как сломанный расчёт.
    """
    if abs(delta) < eps:
        return ""
    col = "var(--good)" if delta > 0 else "var(--bad)"
    sign = "+" if delta > 0 else "−"
    tail = f" {C.esc(unit)}" if unit else ""
    return f'<b style="color:{col}">{sign}{C.fmt_num(abs(delta), digits=digits)}{tail}</b>'


def _wow_pp(delta: float | None) -> str:
    """Изменение выполнения плана — в процентных пунктах.

    Именно в пунктах, а не в процентах: 95% → 97% это «+2 п.п.», а не «+2%».
    Проценты от процентов в отчёте про выполнение плана читаются неверно.
    """
    if delta is None or abs(delta) < 0.0005:
        return ""
    col = "var(--good)" if delta > 0 else "var(--bad)"
    sign = "+" if delta > 0 else "−"
    # запятая, а не точка: дробь в русском отчёте пишется через запятую
    return (f'<b style="color:{col}">{sign}'
            f'{abs(delta) * 100:.1f}'.replace(".", ",") + ' п.п.</b>')


def _wow_chip(a: analyze.Analysis, key: str, unit: str, scale: float = 1.0,
              digits: int = 0, eps: float = 0.5) -> str:
    """Изменение прогноза к прошлой сборке — ПРЯМО В СТРОКЕ показателя, сразу за
    отклонением от плана.

    Зачем здесь, а не только отдельной строкой ниже: отклонение от плана
    отвечает «сколько не хватает», но не отвечает «идём мы к плану или от него».
    Второй вопрос — первый, который задают по плашке, и ответ на него должен
    стоять рядом с числом, а не абзацем ниже.

    ПЕРИОД НАЗЫВАЕТСЯ ЧИСЛОМ ДНЕЙ, а не словом «неделя». Базовая сборка берётся
    по правилу «самая свежая из достаточно старых» (см. snapshot.load_base), и
    на деле ей бывает и пять дней, и девять: подписать такое «за неделю» —
    значит соврать в обе стороны. Если возраст базы неизвестен, вместо периода
    стоит её дата.

    Разделитель « · » живёт ВНУТРИ приписки: без изменения приписки нет вовсе, и
    висящая точка в конце строки не останется.
    """
    w = a.wow or {}
    d = w.get(key) or {}
    if not d:
        return ""
    txt = _wow_num(float(d.get("fc") or 0) / scale, unit, digits, eps)
    if not txt:
        return ""
    days = w.get("days")
    period = (f"за {days} {C.plural(days, 'день', 'дня', 'дней')}" if days
              else f"к сборке от {C.esc(w.get('full', ''))}")
    was = float((w.get("was") or {}).get(key) or 0) / scale
    now = float((a.verdict.get(key) or {}).get("fact") or 0) / scale
    tip = (f' title="прогноз на {C.esc((a.dates or {}).get("label", ""))}: '
           f'{C.fmt_num(was, digits=digits)} {C.esc(unit)} в сборке от '
           f'{C.esc(w.get("full", ""))} → {C.fmt_num(now, digits=digits)} '
           f'{C.esc(unit)} сейчас"')
    return f'<span class="wow-i"{tip}> · {period} {txt}</span>'


def _wow_row(a: analyze.Analysis) -> str:
    """Строка-основание под плашкой прогноза: с чем сравниваются приписки.

    Сравнение идёт с прошлой СБОРКОЙ отчёта: в витрине недельного грейна нет
    (см. snapshot.py). Поэтому дата базовой сборки и её возраст подписаны прямо
    в строке — без них непонятно, за какой период показаны изменения.

    ПРОГНОЗА В СТРОКЕ НЕТ НАМЕРЕННО: его изменение стоит выше, в самих строках
    получателей и ФОТ (см. `_wow_chip`), и повторять его здесь — значит сказать
    одно и то же дважды в трёх строках. Здесь остаётся то, чего в строках
    показателей нет: менялись ли за это время план и выполнение.

    Строка выводится ВСЕГДА, когда база есть, даже если ничего не изменилось:
    она объясняет период у приписок выше. Нет базы — нет и строки.
    """
    w = a.wow or {}
    if not w.get("rcp"):
        return ""
    rcp = w["rcp"]
    parts = []
    plan = _wow_num(rcp.get("plan", 0), "чел")
    if plan:
        parts.append(f"план {plan}")
    ex = _wow_pp(rcp.get("exec"))
    if ex:
        parts.append(f"выполнение {ex}")
    days = w.get("days")
    age = f" ({days} {C.plural(days, 'день', 'дня', 'дней')} назад)" if days else ""
    body = (": " + " · ".join(parts) if parts
            else " — план и выполнение не изменились")
    return (f'<div class="row2 wow">Неделя к неделе, к сборке от '
            f'{C.esc(w["full"])}{age}{body}</div>')


def _wow_unit(a: analyze.Analysis, unit_id: int, cls: str = "g-wow") -> str:
    """То же сравнение по одной единице — для карточки и шапки её разбора."""
    w = a.wow or {}
    u = (w.get("units") or {}).get(unit_id)
    if not u:
        return ""
    parts = []
    fc = _wow_num(u["fc"], "чел")
    if fc:
        parts.append(f"прогноз {fc}")
    ex = _wow_pp(u.get("exec"))
    if ex:
        parts.append(f"выполнение {ex}")
    if not parts:
        return ""
    tip = (f' title="прогноз в сборке от {C.esc(w.get("full", ""))}: '
           f'{C.fmt_num(u["was"])} чел"' if u.get("was") else "")
    return (f'<div class="{cls}"{tip}>Неделя к неделе (к {C.esc(w.get("label", ""))}): '
            + " · ".join(parts) + '</div>')


def _delta_html(delta: float, unit: str = "") -> str:
    """Отклонение от плана в абсолюте: знак, цвет, единица.

    Показывается рядом с процентом везде, где стоит выполнение плана. Ноль в пределах
    округления пишем как «вровень с планом», иначе рядом с «100%» стояло бы «+0».
    """
    if abs(delta) < 0.5:
        return '<b style="color:var(--text-2)">без отклонения</b>'
    col = "var(--good)" if delta > 0 else "var(--bad)"
    sign = "+" if delta > 0 else "−"
    tail = f" {C.esc(unit)}" if unit else ""
    return f'<b style="color:{col}">{sign}{C.fmt_num(abs(delta))}{tail} к плану</b>'


def _kpis(a: analyze.Analysis) -> str:
    """Две карточки по метрикам: сверху ПРОГНОЗ против плана, снизу — твёрдые факты
    ЗАКРЫТОГО месяца и прирост год к году. Разделены линией, потому что это разные по
    природе числа: прогноз может не сбыться, факт закрытого месяца — уже нет."""
    d = a.dates or {}
    closed = a.closed or {}
    yoy = a.yoy or {}

    def foot(key, scale, unit):
        cl = closed.get(key, {})
        if not cl.get("fact"):
            return ""
        # выполнение закрытого месяца окрашено тем же правилом, что и выполнение
        # прогноза строкой выше: это одна и та же величина за разные месяцы, и
        # чёрный процент рядом с цветным читался как другая по смыслу цифра
        head = (f'{C.esc(d.get("closed_label", ""))} закрыт: '
                f'{C.fmt_num(cl["fact"] / scale, unit)} '
                f'(<b style="color:{_col(cl.get("exec"))}">'
                f'{_pct(cl.get("exec"))}</b> плана, '
                + _delta_html((cl["fact"] - cl.get("plan", 0)) / scale, unit) + ')')
        y = yoy.get(key)
        if not y:
            # год к году не рассчитан — честное «—», а не молчаливый ноль
            tail = 'год к году —'
        else:
            col = "var(--good)" if y["delta"] >= 0 else "var(--bad)"
            sign = "+" if y["delta"] >= 0 else "−"
            tail = (f'год к году <b style="color:{col}">{sign}'
                    f'{C.fmt_num(abs(y["delta"]) / scale, unit)} '
                    f'({sign}{abs(y["pct"]) * 100:.1f}%)</b>')
        return f'<div class="foot">{head}<br>{tail}</div>'

    def kpi(title, v, key, scale=1.0, unit=""):
        return C.card(
            f'<div class="label">{C.esc(title)}</div>'
            f'<div class="value">{C.fmt_num(v["fact"] / scale, unit)}</div>'
            f'<div class="delta">план {C.fmt_num(v["plan"] / scale, unit)} · '
            f'<b style="color:{_col(v["exec"])}">{_pct(v["exec"])}</b> · '
            + _delta_html((v["fact"] - v["plan"]) / scale, unit) + '</div>'
            + C.meter(v["exec"]) + foot(key, scale, unit),
            cls="kpi",
        )
    # ФОТ в БД — рубли, выводим в млн ₽ (÷ 1e6)
    cards = (kpi("Получатели (прогноз), чел", a.verdict["rcp"], "rcp")
             + kpi("Общий ФОТ (прогноз), млн ₽", a.verdict["fot"], "fot", scale=1e6))
    return f'<div class="grid cols-2">{cards}</div>'


def _wf_lines(pf: dict, d: dict, conv: float, conv_diag: dict | None = None,
              conv_is_tb: bool = False) -> str:
    """Строки блока портфеля. Общие для уровня и для оверлея по единице — числа
    и порядок одни и те же, меняется только срез данных.

    Пайплайна здесь больше нет — ни строкой, ни подписью: по решению заказчика
    ожидаемый приход по сделкам из отчёта убран на всех уровнях. Расчёт он не
    покинул (в отборе организаций приход по сделкам вычитается из потенциала,
    чтобы не посчитать одних и тех же людей дважды), но читателю не показывается.
    `conv`, `conv_diag` и `conv_is_tb` остаются в сигнатуре — это диагностика
    коэффициента реализуемости, она нужна вызывающим местам и логу сборки.
    """
    out_lbl = C.esc(d.get("out_label", ""))
    rows = [
        (f'Портфель — {C.esc(d.get("closed_label", ""))} закрыт', pf["base"], 0, ""),
        (f'Фактический отток за 3 месяца, который не вернулся',
         pf.get("out_kept", 0), -1,
         # имени витрины в подписи нет: читателю отчёта оно ничего не объясняет,
         # а условие отбора объясняет
         f'{out_lbl} · организации от {bank.OUT_MIN_QTY} чел '
         f'за вычетом вернувшихся' if out_lbl else ""),
    ]
    # подсказка идёт классом g-hint, а НЕ .sub: .sub — это стиль подзаголовка
    # страницы (19px), внутри строки блока он выглядит крупнее самой строки
    return "".join(
        f'<div class="g-seg"><b>{lbl}</b> '
        f'<span style="color:{"var(--bad)" if sign < 0 else "var(--good)"}">'
        f'{"−" if sign < 0 else "+" if sign > 0 else ""}{C.fmt_num(val)}</span>'
        + (f' <span class="g-hint">· {hint}</span>' if hint else "") + '</div>'
        for lbl, val, sign, hint in rows)


def _portfolio_block(a: analyze.Analysis, ai: str | None = None) -> str:
    """Управление портфелем: что есть и что потеряли.

    Это НЕ разложение прогноза на слагаемые. Прогноз берётся готовым из витрины
    метрик и с этими числами арифметически не связан — складывать их и сверять с
    прогнозом бессмысленно. Здесь два независимых факта, каждый со своим
    действием: портфель — что защищаем, невозвращённый отток — что уже потеряли.
    """
    pf = a.pf or {}
    if not pf:
        return ""
    d = a.dates or {}
    fc = a.fc_stats or {}
    body = _wf_lines(pf, d, fc.get("conv_tb", 1.0), fc.get("conv"), conv_is_tb=False)
    st = C.status_of(pf.get("exec"))
    total = (
        f'<div class="g-do">Прогноз на {C.esc(d.get("label", ""))}: '
        f'<b>{C.fmt_num(pf["forecast"])}</b> при плане {C.fmt_num(pf["plan"])} → '
        + C.badge(f"{_pct(pf.get('exec'))} плана", st) + '</div>'
    )
    # Пояснение нужно: без него строки ниже принимают за слагаемые прогноза и
    # начинают сверять их сумму с ним. Но объяснять методику двумя фразами с тире
    # и тройкой однородных — значит писать не читателю, а в протокол.
    note = ('<p class="sub" style="font-size:14px;margin:-4px 0 12px">'
            'Показатели ниже в прогноз не суммируются. Прогноз приходит '
            'готовым, а это независимые факты управления портфелем: '
            'текущая база и безвозвратные потери.</p>')
    return C.section("Управление портфелем",
                     _ai(ai)
                     + C.card('<h3>Портфель и потери</h3>' + note + body + total),
                     eyebrow="Справочно")


def _trend_block(rows: list, title: str) -> str:
    """Два графика и числа под ними: портфель по месяцам и выполнение плана.

    Графики разные не для разнообразия: на линиях видно, куда идёт портфель, но
    разница с планом в проценты там незаметна — её показывают столбцы отклонения от
    нуля. Один график вместо двух отвечал бы только на половину вопроса.
    """
    if not rows:
        return ('<div class="gd-note">истории по этой единице нет — '
                'графики не построены</div>')
    cap = ('Портфель получателей помесячно, человек: факт и изменение к '
           'прошлому месяцу' if C.no_plan_all(rows) else
           'Портфель получателей помесячно, человек: факт, план и отклонение '
           'от плана')
    return (
        f'<h4>{C.esc(title)}</h4>'
        f'<div class="ch-cap">{cap}</div>'
        + C.trend_plan_fact(rows)
        + C.trend_table(rows)
    )


def _trend_verdict(a: analyze.Analysis) -> str:
    """Вывод «Динамики»: что происходит с портфелем и что делать, чтобы он вырос.

    Раздел читают, чтобы отличить разовое отклонение от тенденции, а по графику
    это видно не сразу: двенадцать точек, и глаз цепляется за последнюю. Вывод
    отвечает на тот же вопрос числами — куда идёт портфель, сколько месяцев
    подряд план не выполняется и куда идти за причиной.

    С планом сравниваются ТОЛЬКО месяцы текущей методики. В месяцах, где
    выполнение считалось по балансу, план приравнен к факту: фраза «план
    выполнен во всех 12 месяцах» говорила бы о вычитании, а не о результате
    работы, и прямо противоречила бы выполнению закрытого месяца в плашке.

    Считается арифметикой по тем же строкам, что и график: модель здесь ничего
    не добавит, а расхождение вывода с графиком было бы дороже любых слов.
    """
    rows = a.trend or []
    if len(rows) < 2:
        return ""
    first, last = rows[0], rows[-1]
    grew = last["fact"] - first["fact"]
    cmp_rows = [r for r in rows if not r.get("no_plan")]
    n_miss = sum(1 for r in cmp_rows if r["fact"] < r["plan"])
    streak = 0
    for r in reversed(cmp_rows):
        if r["fact"] < r["plan"]:
            streak += 1
        else:
            break
    lines = [
        f'<b>Что происходит с портфелем.</b> За {C.esc(first["label"])} — '
        f'{C.esc(last["label"])} портфель '
        f'<b style="color:{"var(--good)" if grew >= 0 else "var(--bad)"}">'
        f'{"+" if grew >= 0 else "−"}{C.fmt_num(abs(grew))}</b> чел '
        f'({"рост" if grew >= 0 else "снижение"} на '
        f'{abs(grew) / first["fact"] * 100:.1f}% к началу периода).'
        if first["fact"] else
        f'<b>Что происходит с портфелем.</b> За {C.esc(first["label"])} — '
        f'{C.esc(last["label"])} портфель изменился на '
        f'{"+" if grew >= 0 else "−"}{C.fmt_num(abs(grew))} чел.'
    ]
    if len(rows) >= 4:
        near = last["fact"] - rows[-4]["fact"]
        down = [r["label"] for i, r in enumerate(rows[1:], 1)
                if r["fact"] < rows[i - 1]["fact"]]
        tail = (f' Месяцев со снижением за период: {len(down)}.' if down
                else ' Снижения ни в одном месяце периода не было.')
        lines.append(f'За последние три месяца портфель '
                     f'{"вырос" if near >= 0 else "снизился"} на '
                     f'<b>{C.fmt_num(abs(near))}</b> чел.' + tail)
    if cmp_rows and streak:
        gap = max(0.0, cmp_rows[-1]["plan"] - cmp_rows[-1]["fact"])
        lines.append(f'План не выполняется <b>{streak}</b> '
                     + _plural(streak, "месяц", "месяца", "месяцев")
                     + f' подряд, в {C.esc(cmp_rows[-1]["label"])} не хватает '
                       f'<b>{C.fmt_num(gap)}</b> чел.')
    elif cmp_rows and n_miss:
        lines.append(f'План не выполнялся в {n_miss} из {len(cmp_rows)} '
                     + _plural(len(cmp_rows), "месяца", "месяцев", "месяцев")
                     + f' с планом по текущей методике, в '
                       f'{C.esc(cmp_rows[-1]["label"])} выполнен.')
    elif cmp_rows:
        lines.append(f'План выполнен во всех {len(cmp_rows)} '
                     + _plural(len(cmp_rows), "месяце", "месяцах", "месяцах")
                     + ' с планом по текущей методике.')
    else:
        # Весь показанный период — прежняя методика. Молчать об этом нельзя:
        # график без линии плана иначе читается как «план просто не показали».
        y, m, _ = queries.METRIC_SWITCH_DT.split("-")
        lines.append(f'С планом эти месяцы не сравниваются: план по текущей '
                     f'методике — баланс и закрепление — считается с '
                     f'{C.month_ru(f"{m}.{y}", "gen")}, а за более ранние '
                     f'месяцы он приравнивался к факту. Выполнение плана '
                     f'смотрите по закрытому месяцу в плашке прогноза и в '
                     f'матрице выполнения.')
    # Второй главный вопрос. Ответ на него у динамики всегда один по форме —
    # где смотреть источник роста, — но адрес зависит от того, что показал
    # период: устойчивое отклонение, разовое или рост без плана.
    where = (f'матрица выполнения {C.esc(a.unit_label)}/сегмент — там видно, '
             f'в каких сегментах теряем')
    if streak >= 2:
        lines.append(f'<b>Что делать, чтобы портфель увеличился.</b> Отклонение '
                     f'устойчивое, разовой отработкой оно не закрывается: '
                     f'{where}; кого именно вернуть — в разделе «Отток», кого '
                     f'привлечь — в потенциале организаций.')
    elif n_miss:
        lines.append(f'<b>Что делать, чтобы портфель увеличился.</b> Сверить '
                     f'месяцы с невыполнением плана с матрицей выполнения: '
                     f'отклонение обычно держится в одних и тех же сегментах. '
                     f'Источники роста — возврат ушедших и потенциал '
                     f'организаций.')
    else:
        lines.append(f'<b>Что делать, чтобы портфель увеличился.</b> Темп роста '
                     f'держится, задача — не потерять набранное: {where}, '
                     f'возврат ушедших — в разделе «Отток», новые получатели — '
                     f'в потенциале организаций.')
    body = "".join(f'<p style="margin:0 0 8px">{t}</p>' for t in lines)
    return C.card('<div class="ai-head">Вывод</div>' + body, cls="ai")


def _method_note() -> str:
    """Почему ранние месяцы выполнены ровно на 100%.

    Методика сменилась в середине года, и без этой строки читатель видит у всех
    банков одинаковые 100% и считает это ошибкой расчёта. Строка короткая и
    стоит там же, где числа: сноска внизу раздела до читателя не доходит.
    """
    y, m, _ = queries.METRIC_SWITCH_DT.split("-")      # 2026-07-01 → «июля 2026»
    cut = C.month_ru(f"{m}.{y}", "gen")
    return (f'<p class="gd-note" style="margin:0 0 10px">Помесячный план '
            f'показан только там, где он есть по текущей методике — по балансу '
            f'и закреплению, с {cut}. За более ранние месяцы выполнение '
            f'считалось только по балансу и план приравнивался к факту: '
            f'сравнивать его с фактом нечем, поэтому вместо выполнения стоит '
            f'прочерк, а не 100%. Выполнение закрытого месяца в плашке '
            f'прогноза и в таблицах по сети посчитано по текущей методике — с '
            f'этими месяцами оно не сравнивается. На накопительное выполнение '
            f'за год влияют обе части.</p>')


def _trend_section(a: analyze.Analysis) -> str:
    """Раздел «Динамика за 12 месяцев» — по области уровня целиком.

    Стоит сразу после управления портфелем: там сказано, что с портфелем сейчас,
    здесь — как он к этому пришёл. Только ЗАКРЫТЫЕ месяцы: факт текущего набегает
    в течение месяца и на графике выглядел бы обвалом.
    """
    if not a.trend:
        return ""
    # Отдельной вводной строки здесь нет: те же три числа — период, изменение
    # портфеля и месяцы без выполнения плана — стоят в выводе выше, и читать их
    # дважды подряд незачем.
    # Сноска о методике нужна там, где в таблице есть и сравнимые месяцы, и
    # несравнимые. Если план по текущей методике не захватил ни одного месяца
    # периода, то же самое уже сказано в выводе — второй раз подряд это читается
    # как ошибка вёрстки.
    note = "" if C.no_plan_all(a.trend) else _method_note()
    desc = ("Как портфель получателей менялся месяц к месяцу — чтобы отличить "
            "разовое отклонение от устойчивой тенденции."
            if C.no_plan_all(a.trend) else
            "Как портфель получателей менялся месяц к месяцу и в каких месяцах "
            "план не выполнялся — чтобы отличить разовое отклонение от "
            "устойчивой тенденции.")
    return C.section(
        "Динамика за 12 месяцев",
        _trend_verdict(a) + note + C.card(_trend_block(a.trend, "")),
        eyebrow="Ретроспектива портфеля", desc=desc)


def _matrix(a: analyze.Analysis, ai: str | None = None, idx: int = 0) -> str:
    m = a.matrix
    if m.empty:
        return ""
    # Порядок строк — алфавитный, как и карточки единиц: матрицу читают, отыскивая
    # в ней конкретный ГОСБ. Ранжированный взгляд на те же данные даёт таблица
    # «ТОП по невыполнению» справа.
    gg = a.gosb_gap.assign(_ord=[analyze._ru_key(x) for x in a.gosb_gap["unit_name"]]) \
                   .sort_values("_ord", kind="stable")
    present = set(m.unit_id)
    rows_id_label = [(int(r.unit_id), (r.unit_name or "")[:26])
                     for r in gg.itertuples() if int(r.unit_id) in present]
    segs = [s for s in SEG_ORDER if s in set(m.seg_name)]
    # Красная ячейка = западающий сегмент из карточек единицы: тот же порог в одного
    # получателя (недобор меньше человека — округление, показываем как выполнено).
    cells = {(int(row.unit_id), row.seg_name):
             (row.execution_percent if analyze._failing_seg(row.nedobor) else
              max(float(row.execution_percent or 0), 1.0), row.nedobor)
             for row in m.itertuples()}
    # Ранг есть только у ТБ — это величина витрины, считанная по закрытому месяцу.
    # На уровне ТБ единицы строк — ГОСБ, и колонки ранга там нет.
    ranks = a.ranks if a.level == "sb" else None
    hint = ('<p class="sub" style="font-size:14px;margin:-4px 0 12px">'
            'Клик по ячейке открывает организации этого '
            f'{C.esc(a.unit_label)} и сегмента, у которых за год стало меньше '
            'получателей.'
            + (' Ранг — место ТБ в сети по выполнению плана за закрытый месяц '
               f'{C.esc((a.dates or {}).get("closed_label", ""))}.' if ranks else "")
            + '</p>')
    heat = C.card(
        '<h3>Прогноз выполнения плана по получателям, %</h3>' + hint
        + C.heat_matrix(rows_id_label, segs, cells, unit_head=a.unit_label,
                        ranks=ranks, cell_click="cellOpen",
                        head_hints=segments.HINT))
    top = [(f'{r.unit_name} · {r.seg_name}',
            C.badge(_pct(r.execution_percent), C.status_of(r.execution_percent)),
            C.fmt_num(r.nedobor), f'{r.share*100:.0f}%') for r in a.top_cells.itertuples()]
    # «ГОСБхСегмент» — и на уровне банка тоже: так в дизайне пользователя
    # Единица в шапке — та же, что в самой таблице: на уровне банка строки это
    # «ТБ × сегмент», и подпись «ГОСБ × сегмент» над ними читалась как ошибка.
    n_fail = int((m["nedobor"] > 0).sum())
    rest = (f' Показаны {len(top)} крупнейших из {n_fail} пар с отклонением — '
            f'на них приходится {sum(r.share for r in a.top_cells.itertuples())*100:.0f}% '
            f'суммарного отклонения.' if n_fail > len(top) else "")
    top_tbl = C.card(
        f'<h3>ТОП {a.unit_label} по невыполнению</h3>'
        '<p class="sub" style="font-size:14px;margin:-4px 0 12px">'
        'Доля — часть суммарного отклонения всех пар «подразделение × сегмент» '
        'этого уровня: видно, сколько из общего отклонения приходится на строку.'
        f'{rest}</p>'
        + C.table([f"{C.esc(a.unit_label)} × сегмент", "Выполн.",
                   "Отклонение, чел", "Доля отклонения"],
                  top, num_cols=[2, 3]))
    # Выгрузка раздела — книгой из трёх листов. На экране матрица отвечает на
    # вопрос «где», а построчный разбор до организации — работа в Excel: в
    # разметку он не едет, берётся из того же словаря, что и раскрытие ячейки.
    dl = ('<div class="of-flt"><span class="of-flt-l">Раздел целиком:</span>'
          '<button type="button" class="of-detail" onclick="mxXls(this)" '
          'title="Книга из трёх листов: матрица, ТОП по невыполнению и '
          'детализация по организациям">'
          'Выгрузить в Excel: матрица и детализация</button></div>')
    return C.section(f"Матрица выполнения {a.unit_label}/сегмент",
                     _ai(ai) + dl
                     + f'<div class="grid cols-2">{heat}{top_tbl}</div>'
                     + _cell_data(a, idx, cells),
                     eyebrow="Диагностика по прогнозу")


def _cell_data(a: analyze.Analysis, idx: int, cells: dict) -> str:
    """Состав ячеек матрицы — данными для скрипта, а не разметкой.

    Ячеек на уровне до шестисот, и разложить каждую отдельным скрытым блоком
    значило бы утроить вес файла ради содержимого, которое открывают у двух-трёх
    ячеек. Поэтому в документ уезжает компактный словарь, а разметку строит
    `cellOpen` в момент клика.

    Ключ — «единица|сегмент» в пределах уровня; сам уровень скрипт узнаёт по
    id блока, внутри которого лежит матрица: в одном файле тринадцать отчётов.
    """
    top = a.cell_top or {}
    if not top:
        return ""
    payload = {}
    for key in cells:
        cell = top.get(key)
        if not cell:
            continue
        uid, seg = key
        payload[f"{uid}|{seg}"] = {
            "n": cell["n"], "fl": round(cell["fl"]),
            "top": round(cell.get("top_fl", 0)),
            # номер организации идёт ПОСЛЕДНИМ: оверлей читает строку по
            # индексам, и вставка в середину сдвинула бы ему все колонки
            "rows": [[r["name"], round(r["yoy"]), round(r["cur"]), round(r["was"]),
                      r["emp"], str(r["inn"]),
                      round((r.get("move") or {}).get("fl", 0)),
                      _move_text(r.get("move"))] for r in cell["rows"]],
        }
    if not payload:
        return ""
    holder, expr = veil.hide(payload, f"d-cells-{idx}")
    return (f'{holder}<script>window.__CELLS=window.__CELLS||{{}};'
            f'window.__CELLS["lvl-{idx}"]={expr};</script>')


def _gap_cell(v: float) -> str:
    """Ячейка недобора. План выполнен (недобор ≤ 0) — ставим «—», а не «−0»."""
    return "—" if v <= 0.5 else "−" + C.fmt_num(v)


def _seg_badge(s: dict) -> str:
    """Бейдж сегмента: имя + выполнение, цвет по статусу — состояние не кодируется
    одним лишь цветом. При 99.5–99.9% показываем десятую долю, иначе рядом с
    недобором стояло бы «100%»."""
    return C.badge(f'{s["seg"]} {_pct(s["exec"])}', C.status_of(s["exec"]))


def _gosb_table(c: dict) -> str:
    """Таблица карточки: строка «Всего» по ГОСБ + строки ВСЕХ сегментов.

    Одни и те же колонки на обоих уровнях — итог и сегменты сравниваются по вертикали.
    Выполняющие сегменты идут ниже западающих и приглушены: видно, за счёт чего ГОСБ
    вытягивает план, но взгляд по-прежнему цепляется за проблемные.
    У строки «Всего» бейджа нет — процент уже стоит крупно в шапке карточки.

    Колонки пайплайна в таблице больше нет — ожидаемый приход по сделкам убран
    из отчёта. Оттока по сегментам здесь нет: фактический отток лежит на грейне (ГОСБ, ИНН)
    и в разрез витрины по сегментам не раскладывается — разносить его
    пропорционально было бы выдумкой.
    """
    def row(label, d, cls=""):
        return (f'<div class="g-row {cls}"><span>{label}</span>'
                f'<span>{C.fmt_num(d["forecast"])}</span>'
                f'<span>{C.fmt_num(d["plan"])}</span>'
                f'<span>{_gap_cell(d["nedobor"])}</span>'
                f'<span>{d.get("n_need") or "—"}</span></div>')

    head = ('<div class="g-row head"><span>сегмент</span><span>прогноз</span>'
            '<span>план</span><span>отклонение</span><span>орг</span></div>')
    tot = {"forecast": c["forecast"], "plan": c["plan"], "nedobor": c["gap"],
           "n_need": c["n_need"]}
    rows = [row(_seg_badge(s), s, "" if s["failing"] else "ok") for s in c["segs"]]
    if not rows:
        rows.append('<div class="g-row"><span>нет данных по сегментам</span></div>')
    rest = row("прочие", c["rest"], "rest") if c.get("rest") else ""
    return (f'<div class="g-tbl">{head}{row("Всего", tot, "total")}'
            f'{"".join(rows)}{rest}</div>')


def _org_rows(rows: list, key: str, tail_n: int, tail_fl: float,
              tail_txt: str, sign: int = -1, why=None,
              cover: float = 0.0, n_all: int = 0, with_emp: bool = False) -> str:
    """Строки именной детализации: организация · вклад · причина и что сделать.

    Названия компаний приходят из БД — обязательно через C.esc. Оттуда же ФИО
    закреплённого сотрудника (`emp`).

    `with_emp` — показывать ли ФИО. Флагом, а не «есть ли поле в строке»: строками
    одного и того же кадра живут два блока (отток и годовой тренд), поле несут
    оба, а подпись нужна только оттоку. Кто её показывает, видно по вызовам.

    Хвост не прячем, и покрытие тоже: подпись всегда говорит, сколько организаций из
    общего числа показано и какую долю блока они объясняют. На проме в блоке бывает
    несколько тысяч организаций, и 8 названных могут объяснять лишь пятую часть —
    читатель обязан это видеть, иначе примет часть за целое.
    """
    if not rows:
        return '<div class="gd-note">нет организаций с заметным вкладом</div>'
    # пояснение зависит от блока: причина оттока к годовому тренду отношения не
    # имеет, поэтому текст задаётся вызывающим
    why_fn = why or (lambda r: " · ".join(x for x in (r.get("note"), r.get("action")) if x))
    out = []
    if cover and n_all > len(rows):
        out.append(f'<div class="gd-note">{len(rows)} из {C.fmt_num(n_all)} орг. — '
                   f'это {cover * 100:.0f}% блока</div>')
    for r in rows:
        mark = "−" if sign < 0 else "+"
        # ФИО закреплённого сотрудника — второй строкой под названием, как «Орг. N»
        # в списке к работе. Отдельной колонкой его не сделать: строка организации и
        # шапка группы размечены ОДНОЙ сеткой в три колонки, четвёртая разъехалась бы
        # в обеих. Пусто на уровне СБ: там единица разбора ТБ, а закрепление живёт
        # на грейне (ГОСБ, организация) — см. analyze._unit_detail.
        emp = str(r.get("emp") or "").strip() if with_emp else ""
        # span, а не div: ячейка сетки — сам <span>, а блочный элемент внутри
        # фразового делает разметку невалидной. Перевод строки даёт CSS
        sub = f'<span class="gd-emp">{C.esc(emp)}</span>' if emp else ""
        out.append(
            f'<div class="gd-row"><span>{_HID.text(r["name"])}{sub}</span>'
            f'<span>{mark}{C.fmt_num(abs(r[key]))}</span>'
            f'<span class="gd-why">{C.esc(why_fn(r)) or "—"}</span></div>')
    if tail_n:
        out.append(f'<div class="gd-note">ещё {C.fmt_num(tail_n)} орг. на '
                   f'{C.fmt_num(tail_fl)} чел {C.esc(tail_txt)}</div>')
    return "".join(out)


def _why_out(r: dict) -> str:
    """Пояснение к строке оттока: сколько вернулось, вывод по отработке, что делать.

    Пометка о зоне нужна именно здесь: в списке крупнейших неизбежно окажутся
    организации, с которыми работать нельзя (нет в эталонной базе) или нечем — отток
    уже отработан, а люди не вернулись. Без пометки читатель начнёт распределять то,
    что не его.

    `reason` — вывод аудита, если он был, иначе причина классификации: для возвратных
    организаций она названа по МЕСЯЦАМ УХОДА («задач не заводили», «ни одной по
    оттоку», «отработан»), и именно она объясняет, почему строка здесь.
    """
    back = float(r.get("ret", 0) or 0)
    parts = []
    if back:
        parts.append(f'вернулись {C.fmt_num(back)} из {C.fmt_num(r.get("gone", 0))}')
    parts += [x for x in (r.get("reason"), r.get("action")) if x]
    zone = r.get("zone")
    if zone and zone != "можно работать":
        parts.insert(0, zone)
    return " · ".join(parts) if parts else "причина не зафиксирована"


def _why_size(r: dict) -> str:
    """Пояснение к строке годового тренда: когда оттекали, работали ли тогда, причина.

    Про отработку говорим ровно то, что знаем: «задач не заводили» — это факт из
    выборки, «отработка неизвестна» — месяц оттока в окно воронки не попал. Подменять
    второе первым нельзя, это разные утверждения.
    """
    parts = [f'сейчас {C.fmt_num(r["cur"])} чел']
    months = r.get("out_months") or []
    if months:
        shown = ", ".join(months[:3])
        more = f" и ещё {len(months) - 3}" if len(months) > 3 else ""
        parts.append(f"отток: {shown}{more}")
        if r.get("yoy_key") == "unknown":
            parts.append("отработка за те месяцы неизвестна")
        elif r.get("yoy_tasks"):
            # задачи считаются и в самом месяце оттока, и в следующем: витрина
            # закрывает отток позже, чем он случился, и задачу заводят обоими
            parts.append(f'задач в те месяцы и следующие за ними: {r["yoy_tasks"]}')
        else:
            parts.append("задач ни в те месяцы, ни в следующие не заводили")
    else:
        parts.append("заметных оттоков за окно не было")
    parts.append(f'причина: {r["reason"]}' if r.get("reason") else "причина не зафиксирована")
    return " · ".join(parts)


def _out_group(g: dict) -> str:
    """Группа оттока: шапка с причиной и итогом, внутри — список организаций.

    Нативный `<details>`: клик и клавиатура работают без JS, а печать раскрывает
    содержимое сама. Шапка размечена теми же тремя колонками, что и строка
    организации, — числа групп и числа организаций стоят в одной вертикали.

    Покрытие внутри списка не подписываем: сколько организаций в группе и сколько
    в них человек, уже сказано в шапке — повторять это строкой ниже незачем.
    """
    work = (f'можно работать: {g["work_n"]} орг (−{C.fmt_num(g["work_fl"])})'
            if g["work_n"] else "работать не с кем — вне зоны влияния")
    return _group_html(g, work, "out", _why_out, with_emp=True)


def _yoy_group(g: dict) -> str:
    """Группа годового тренда. Тот же рендер, что у оттока, — меняется только то,
    что стоит в третьей строке шапки: у оттока это зона влияния, здесь — сколько
    организаций группы имеют зафиксированную причину."""
    work = (f'причина зафиксирована у {g["work_n"]} орг (−{C.fmt_num(g["work_fl"])})'
            if g["work_n"] else "причина не зафиксирована ни у одной")
    return _group_html(g, work, "yoy", _why_size, with_emp=True)


def _group_html(g: dict, work: str, key: str, why,
                with_emp: bool = False) -> str:
    """Группа: шапка с причиной и итогом, внутри — список организаций.

    Нативный `<details>`: клик и клавиатура работают без JS, а печать раскрывает
    содержимое сама. Шапка размечена теми же тремя колонками, что и строка
    организации, — числа групп и числа организаций стоят в одной вертикали.

    ВСЕ группы свёрнуты. Раньше первая (крупнейшая) открывалась сама, и читатель
    видел её список раньше, чем сами группы: остальные причины оказывались под
    длинной таблицей, и до них не доходили. Свёрнутый вид показывает сразу все
    причины с их весом — выбор, что разворачивать, остаётся за читателем. На
    печати и в выгрузке PDF группы раскрываются целиком, там прятать нечего.

    Покрытие внутри списка не подписываем: сколько организаций в группе и сколько
    в них человек, уже сказано в шапке — повторять это строкой ниже незачем.
    """
    sub = f'{g["sub"]} · {g["share"] * 100:.0f}% блока · {work}'
    return (
        f'<details class="gd-grp" '
        f'style="--share:{g["share"] * 100:.0f}%">'
        f'<summary><span class="gd-gt">{C.esc(g["title"])}'
        f'<i>{g["n"]} орг</i></span>'
        f'<span>−{C.fmt_num(g["fl"])}</span>'
        f'<span class="gd-sub">{C.esc(sub)}</span></summary>'
        f'<div class="gd-rows">'
        + _org_rows(g["rows"], key, g["tail_n"], g["tail_fl"], "— хвост", why=why,
                    with_emp=with_emp)
        + '</div></details>'
    )


# Тексты подсказок «как считаем» — ОДИН раз на документ.
#
# Подсказки одинаковы во всех карточках уровня и повторяются в каждой из сотни
# с лишним: в собранном отчёте на них уходило 430 КБ — семь процентов файла за
# один и тот же текст. Поэтому текст кладётся в словарь документа, а в разметке
# остаётся заголовок и ключ; содержимое подставляется при первом раскрытии
# (см. `_HELP_JS`) и перед выгрузкой в PDF.
_HELP_TEXTS: dict[str, str] = {}

# Подписи организаций не лежат в разметке открытым текстом: после замены имён
# людей на номер там оказывался номер клиента в каждой строке. См. veil.Hidden.
_HID = veil.Hidden("d-text")


def _gd_help(*lines: str, title: str = "Как считаем этот блок") -> str:
    """Подсказка «как считаем» под заголовком блока карточки.

    Нативный `<details>`: закрыта по умолчанию, открывается кликом и с клавиатуры.
    Читателю карточки объяснение нужно один раз, поэтому строкой, а не постоянным
    текстом на пол-экрана.

    Язык подсказки — про смысл числа, а не про источник: названия таблиц и полей
    управляющему ничего не говорят и только удлиняют текст.
    """
    body = "".join(f"<p>{x}</p>" for x in lines if x)
    if not body:
        return ""
    key = f"h{len(_HELP_TEXTS)}"
    for k, v in _HELP_TEXTS.items():          # одинаковый текст — один ключ
        if v == body:
            key = k
            break
    else:
        _HELP_TEXTS[key] = body
    return (f'<details class="gd-help" data-h="{key}">'
            f'<summary>{C.esc(title)}</summary>'
            f'<div class="gd-help-b"></div></details>')


def _help_data() -> str:
    """Словарь подсказок в документ — один раз, после всей разметки."""
    if not _HELP_TEXTS:
        return ""
    holder, expr = veil.hide(_HELP_TEXTS, "d-help")
    return f'{holder}<script>window.__HELP={expr};</script>'


# Подстановка текста подсказки в момент раскрытия.
#
# Без скрипта подсказка окажется пустой, поэтому заголовок остаётся в разметке
# всегда: читатель видит, что объяснение есть. Перед выгрузкой в PDF заполняются
# все сразу — на бумаге раскрывать нечего.
_HELP_JS = """
<script>
(function(){
  function fill(d){
    if(!d || d.dataset.filled === '1') return;
    var box = d.querySelector('.gd-help-b');
    var txt = (window.__HELP || {})[d.dataset.h];
    if(!box || !txt) return;
    box.innerHTML = txt;
    d.dataset.filled = '1';
  }
  document.addEventListener('toggle', function(e){
    var d = e.target;
    if(d && d.classList && d.classList.contains('gd-help') && d.open) fill(d);
  }, true);
  /* клик ловим и на перехвате: toggle всплывает не во всех браузерах */
  document.addEventListener('click', function(e){
    var d = e.target.closest ? e.target.closest('details.gd-help') : null;
    if(d) setTimeout(function(){ fill(d); }, 0);
  }, true);
  window.helpFillAll = function(root){
    (root || document).querySelectorAll('details.gd-help').forEach(fill);
  };
})();
</script>
"""


def _gd_verdict(c: dict, det: dict, d: dict, flow: dict | None,
                unit_id: int, unit_label: str) -> str:
    """Вывод в начале карточки: что с планом, чем это вызвано и что делать.

    Карточку открывают, чтобы принять решение, а не прочитать её целиком: до
    сегментов и оттока доходили не все, а ответ «план закрывается своими
    организациями» или «своих не хватает» нужен сразу. Числа берутся из тех же
    полей, что и блоки ниже, — отдельного расчёта здесь нет, и разойтись им не
    с чем.
    """
    pf = (det or {}).get("pf") or {}
    if not pf:
        return ""
    ex = pf.get("exec")
    plan, fc = pf.get("plan") or 0, pf.get("forecast") or 0
    gap = max(0.0, plan - fc)
    lines = []
    if not plan:
        lines.append(f'Плана по получателям на этот месяц у {C.esc(unit_label)} нет — '
                     f'прогноз {C.fmt_num(fc)} чел.')
    elif gap >= 1:
        lines.append(f'План не выполняется: прогноз <b>{C.fmt_num(fc)}</b> при плане '
                     f'{C.fmt_num(plan)} — <b style="color:{_col(ex)}">{_pct(ex)}</b>, '
                     f'не хватает <b>{C.fmt_num(gap)}</b> чел.')
    else:
        lines.append(f'План выполняется: прогноз <b>{C.fmt_num(fc)}</b> при плане '
                     f'{C.fmt_num(plan)} — <b style="color:{_col(ex)}">{_pct(ex)}</b>, '
                     f'{_delta_html(fc - plan, "чел")}.')

    bad = c.get("segs_bad") or []
    if bad:
        names = ", ".join(f'{C.esc(s["seg"])} (−{C.fmt_num(abs(s["nedobor"]))} чел)'
                          for s in bad[:3])
        tail = (f' и ещё {len(bad) - 3} '
                + _plural(len(bad) - 3, "сегмент", "сегмента", "сегментов")
                if len(bad) > 3 else "")
        where = _plural(len(bad), "сегменте", "сегментах", "сегментах")
        lines.append((f'Общий план вытянут другими сегментами, но не выполняется '
                      f'в {where} {names}{tail}.' if c.get("seg_only")
                     else f'Невыполнение сосредоточено в {where} {names}{tail}.'))
    elif plan:
        lines.append('План выполняется во всех сегментах.')

    if c.get("n_need"):
        filler = (f'; из них в других сегментах подразделения — '
                  f'{c["filler_n"]} орг (+{C.fmt_num(c["filler_fl"])} чел)'
                  if c.get("filler_n") else "")
        lines.append(f'Под план отобрано <b>{c["n_need"]}</b> '
                     + _plural(c["n_need"], "организация", "организации", "организаций")
                     + f' на +{C.fmt_num(c["fl_need"])} чел: привлечь '
                     f'{c["n_attract"]}, вернуть {c["n_return"]}{filler}.')

    out_tot, out_n = det.get("out_tot") or 0, det.get("out_n_all") or 0
    if out_tot:
        yoy = det.get("yoy_total") or 0
        yoy_txt = (f' Год к году портфель {"+" if yoy > 0 else "−"}'
                   f'{C.fmt_num(abs(yoy))} чел.' if yoy else "")
        lines.append(f'Потери за три закрытых месяца '
                     f'({C.esc((d or {}).get("out_label", ""))}) — '
                     f'<b>{C.fmt_num(out_tot)}</b> чел в {C.fmt_num(out_n)} '
                     + _plural(out_n, "организации", "организациях", "организациях")
                     + '.' + yoy_txt)

    u = next((x for x in ((flow or {}).get("units") or [])
              if int(x["id"]) == int(unit_id)), None)
    if u and u.get("base"):
        net = u["net"]
        lines.append(f'Переток за {C.month_ru((flow or {}).get("m_cur", ""))}: '
                     f'перестали получать {C.fmt_num(u["left"])} чел, из них '
                     f'<b>{C.fmt_num(u["gone"])}</b> не получают зарплату нигде; '
                     f'начали {C.fmt_num(u["came"])} — '
                     + ('портфель без изменений.' if abs(net) < 0.5 else
                        f'чистое изменение '
                        f'{"+" if net > 0 else "−"}{C.fmt_num(abs(net))} чел.'))

    if gap >= 1 and c.get("n_need"):
        # «Взять в работу отобранные организации» без чисел — это не поручение,
        # а напоминание. Поручение — это сколько организаций, что они дают и
        # сколько из них пока не в работе.
        nw = int(c.get("not_worked") or 0)
        fl_nw = float(c.get("fl_not_worked") or 0)
        tail = (f'; первоочередной резерв — непривлечённый потенциал '
                f'+{C.fmt_num(fl_nw)} чел по {nw} из них' if nw else '')
        act = (f'Что делать: взять в работу {c["n_need"]} '
               + _plural(c["n_need"], "отобранную организацию",
                         "отобранные организации", "отобранных организаций")
               + f' (+{C.fmt_num(c["fl_need"])} чел), приоритет — сегменты с '
                 f'невыполнением плана{tail}.')
    elif gap >= 1:
        act = ('Что делать: отобранные организации закрывают отклонение не '
               'полностью — отрабатывать список целиком и пополнять воронку '
               'новыми кандидатами.')
    elif bad:
        act = ('Что делать: план в целом выполняется, держать под контролем '
               'сегменты с невыполнением.')
    else:
        act = 'Отработка не требуется: план выполняется во всех сегментах.'
    lines.append(act)

    body = "".join(f'<p style="margin:6px 0 0">{t}</p>' for t in lines)
    return C.card('<div class="ai-head">Вывод</div>' + body, cls="ai gd-sum")


def _gosb_dialog(c: dict, det: dict, d: dict, uid: str, unit_label: str = "ГОСБ",
                 wow: str = "", flow: dict | None = None, unit_id: int = 0) -> str:
    """Оверлей «почему прогноз такой» по одному ГОСБ.

    Порядок блоков: портфель → отток по группам → тренд портфеля →
    разбор по сегментам. Отток разложен на группы (см. `_out_group`) и покрыт целиком;
    в остальных блоках имена показываются только материальные, поэтому у них стоит
    подпись о покрытии.

    Группы в блоках «Отток по причинам» и «Портфель год к году» свёрнуты все до
    одной: карточка открывается перечнем причин с их весом, а список организаций
    читатель разворачивает сам — по той причине, которая его интересует.
    """
    if not det:
        return ""
    pf = det["pf"]
    # у единицы свой коэффициент реализуемости и своя доля пройденного месяца
    wf_html = _wf_lines(pf, d, det["conv"], det.get("conv_diag"),
                        det.get("conv_is_tb", False))
    yoy = det["yoy_total"]
    # Отток разложен по причине, все группы свёрнуты: сначала читатель видит
