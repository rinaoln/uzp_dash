def _problem_gosb(a: analyze.Analysis, ai: str | None = None, idx: int = 0) -> str:
    """Карточки единиц уровня: ГОСБ внутри ТБ, ТБ внутри банка.

    `idx` — номер уровня в документе; из него собираются id оверлеев. В одном файле
    лежат все 13 отчётов, и без префикса id оверлея ГОСБ мог бы совпасть с id
    оверлея ТБ, а клик открывал бы чужую карточку.
    """
    if not a.gosb_cards:
        return ""
    cards, dialogs = [], []
    d = a.dates or {}
    unit = a.unit_label
    for c in a.gosb_cards:
        # Цвет карточки — СТРОГО по выполнению прогноза, тем же правилом, что и
        # везде в отчёте (C.status_of: ≥100% зелёный, 95–100% жёлтый, ниже красный).
        # Раньше здесь было своё правило: единица с выполнением 107% и одним
        # невыполненным сегментом красилась жёлтым, а число «107%» рядом с зелёным
        # 107% в матрице и в плашке читалось как ошибка расчёта. Заодно уходил порог
        # 0.9, из-за которого 92% на карточке были жёлтыми, а в матрице — красными.
        # Про сегменты говорит бейдж ниже: он и остаётся жёлтым, когда план вытянут
        # другими сегментами.
        st = C.status_of(c["exec"])
        seg_html = _gosb_table(c)
        # пояснения по западающим сегментам в строку таблицы не влезают — отдельно
        notes = []
        for s in c["segs_bad"]:
            cov = s["coverage"]
            if not s["n_avail"]:
                notes.append(f'в {s["seg"]} отобранных организаций нет — '
                             f'нужны новые кандидаты в воронку')
            elif cov is not None and cov < 0.999:
                notes.append(f'в {s["seg"]} хватает на {cov*100:.0f}% ({s["n_avail"]} орг)')
        note_html = (f'<div class="g-act">{C.esc(" · ".join(notes[:3]))}</div>'
                     if notes else "")
        act = c["act"]
        if c["healthy"]:
            head_badge = C.badge("план выполняется по всем сегментам", "good")
        elif c["seg_only"]:
            head_badge = C.badge(f'план выполняется, не выполнен в сегментах: '
                                 f'{", ".join(s["seg"] for s in c["segs_bad"][:3])}', "warn")
        else:
            head_badge = C.badge("−" + C.fmt_num(c["gap"]) + " чел до плана", st)
        filler = (f' · из них в других сегментах подразделения: '
                  f'<b>{c["filler_n"]}</b> орг (+{C.fmt_num(c["filler_fl"])})'
                  if c["filler_n"] else "")
        # Знаменатель — отклонение ТОЛЬКО тех сегментов, где план не выполняется:
        # отбор идёт внутри них, и доля от общего отклонения подразделения
        # отвечала бы на другой вопрос. Это сказано в самой строке, иначе
        # процент не сходится с числами выше.
        cover = (c["fl_need"] / c["gap_seg"]) if c["gap_seg"] > 0 else None
        short = (f' · покрывает <b>{cover*100:.0f}%</b> отклонения в сегментах '
                 f'с невыполнением плана ({C.fmt_num(c["gap_seg"])} чел), '
                 f'остальное — за счёт новых кандидатов'
                 if cover is not None and cover < 0.999 else "")
        do = (
            f'<div class="g-do">Итого под план: <b>{c["n_need"]}</b> '
            f'{_plural(c["n_need"], "организация", "организации", "организаций")} '
            f'(+{C.fmt_num(c["fl_need"])} чел, привлечь {c["n_attract"]} / '
            f'вернуть {c["n_return"]}) · ФОТ <b>~{C.fmt_num(c["fot_need"])}</b> млн ₽'
            f'{filler}{short}</div>'
            f'{note_html}'
            f'<div class="g-act">Активности 3 мес: {act["act_n"]} по {act["worked_orgs"]} орг, '
            f'успех {act["success"]*100:.0f}%'
            + (f' · по <b>{c["not_worked"]}</b> из {c["n_need"]} отобранных '
               f'организаций активностей за 3 мес не было'
               if c["n_need"] else "") + '</div>'
        )
        gid = c["gosb_id"]
        uid = f"{idx}-{gid}"           # уникален в пределах документа со всеми уровнями
        det = (a.gosb_detail or {}).get(gid)
        # Подписи «Почему такой прогноз →» на карточке нет: о том, что карточка
        # кликабельна, говорит стрелка в её углу, и она же стоит на карточках без
        # разбора — лишняя строка только удлиняла карточку.
        more = ""
        # на уровне банка карточка ТБ ведёт ещё и в его собственный разбор — это и есть
        # переход СБ → ТБ; onclick останавливаем, чтобы не открылся заодно оверлей
        drill = (f'<div class="g-more g-drill" onclick="event.stopPropagation();'
                 f'lvlGo({c["lvl"]})">Открыть разбор {C.esc(c["gosb_name"])} →</div>'
                 if c.get("lvl") else "")
        # Выполнение прогноза — главное число карточки, поэтому оно стоит крупно,
        # подписано словом и окрашено по статусу. Одного цвета мало: рядом со
        # знаком «%» идёт подпись, а статус продублирован бейджем ниже.
        inner = (
            f'<div class="g-head"><h3 style="margin:0">{C.esc(c["gosb_name"])}</h3>'
            f'<span class="g-ex {st}"><i>прогноз</i>{_pct(c["exec"])}</span></div>'
            + C.meter(c["exec"])
            + f'<div class="g-fc">{C.fmt_num(c["forecast"])} из '
              f'{C.fmt_num(c["plan"])} · {_delta_html(c["forecast"] - c["plan"], "чел")}'
              f'</div>'
            # куда сдвинулся прогноз этой единицы с прошлой сборки: по карточкам
            # видно, где неделя что-то изменила, а где всё стоит на месте
            + _wow_unit(a, gid)
            + f'<div style="margin:2px 0 6px">{head_badge}</div>'
            + f'{seg_html}{do}{more}{drill}'
        )
        # карточка кликабельна целиком; role/tabindex — чтобы работала и с клавиатуры
        attrs = (f' role="button" tabindex="0" onclick="gdOpen(\'{uid}\')" '
                 f'onkeydown="if(event.key===\'Enter\'||event.key===\' \')'
                 f'{{event.preventDefault();gdOpen(\'{uid}\');}}"' if det else "")
        # Ключи сортировки — в самой карточке: порядок по отклонению ставится
        # разметкой, переключатель «по алфавиту» возвращает алфавитный, и ни то
        # ни другое не требует пересборки отчёта.
        # Ключ порядка — ВЫПОЛНЕНИЕ В ПРОЦЕНТАХ, а не отклонение в людях:
        # крупное подразделение с отклонением в тысячу человек может идти на
        # 99%, а небольшое с отклонением в сотню — на 90%, и хуже дела именно
        # у второго. Число людей осталось вторым ключом — для равных процентов.
        ex = float(c["exec"] or 0)
        cards.append((ex, -float(c["plan"] - c["forecast"]),
                      analyze._ru_key(c["gosb_name"]),
                      f'<div class="card gcard {st}" data-exec="{ex:.6f}" '
                      f'data-gap="{c["plan"] - c["forecast"]:.0f}"{attrs}>'
                      f'{inner}</div>'))
        if det:
            dialogs.append(_gosb_dialog(c, det, d, uid, unit,
                                        _wow_unit(a, gid, "gd-wow"),
                                        a.flow, gid))
    # По умолчанию — ХУДШИЕ СВЕРХУ. Алфавит ставил подразделение с наибольшим
    # отклонением в конец списка (ЮЗБ — последний в сети), и управляющий видел
    # его, только долистав до низа. Алфавитный порядок остался переключателем:
    # когда ищут конкретное подразделение, в голове алфавит, а не рейтинг.
    by_gap = sorted(cards, key=lambda x: (x[0], x[1], x[2]))
    html = "".join(x[3] for x in by_gap)
    sort_ui = (
        f'<div class="gc-sort" data-grid="gcards-{idx}">'
        f'<span>Порядок карточек:</span>'
        f'<button type="button" class="gc-sort-b on" data-mode="gap" '
        f'title="худшее выполнение плана сверху">'
        f'по выполнению плана</button>'
        f'<button type="button" class="gc-sort-b" data-mode="abc">'
        f'по алфавиту</button></div>')
    grid = (f'{sort_ui}<div class="gcards" id="gcards-{idx}">{html}</div>'
            f'{"".join(dialogs)}')
    return C.section(f"Детализация по {unit}", _ai(ai) + grid,
                     eyebrow=f"Детализация по {unit} · клик открывает разбор до организаций")


def _gd_flow(flow: dict | None, unit_id: int, unit_label: str) -> str:
    """Переток ФЛ одного подразделения — в его карточке, в разрезе сегментов.

    В разделе переток показан по всем подразделениям уровня, и это отвечает на
    вопрос «у кого хуже». Но работают с подразделением по отдельности, и там
    нужен свой разбор: из каких сегментов ушли люди, где это настоящая потеря,
    а где переход в другую организацию. Детализация та же, что в разделе, —
    иначе два места в отчёте пришлось бы сверять вручную.
    """
    f = flow or {}
    units = {int(u["id"]): u for u in (f.get("units") or [])}
    u = units.get(int(unit_id))
    if not u or not u.get("base"):
        return ""
    # по сегментам: в каждом срезе ищем строку этого подразделения
    srows = []
    for sg in f.get("segs") or []:
        row = next((x for x in (f.get("seg_units") or {}).get(sg) or []
                    if int(x["id"]) == int(unit_id)), None)
        if not row or not row.get("base"):
            continue
        net = row["net"]
        srows.append([
            C.esc(sg),
            C.fmt_num(row["base"]),
            f'<b style="color:var(--bad)">{C.fmt_num(row["left"])}</b>',
            C.fmt_num(row["gone"]),
            C.fmt_num(row["moved"]),
            C.fmt_num(row["below"]),
            C.fmt_num(row["other"]),
            f'<b style="color:var(--good)">{C.fmt_num(row["came"])}</b>',
            (f'<b style="color:{"var(--good)" if net > 0 else "var(--bad)"}">'
             f'{"+" if net > 0 else "−"}{C.fmt_num(abs(net))}</b>' if net else "0")])
    seg_tbl = (C.table(["Сегмент", "было, чел", "перестали", "из них совсем",
                        "в другой организации", "ниже порога", "незарплатные",
                        "начали", "чистое изменение"], srows,
                       num_cols=[1, 2, 3, 4, 5, 6, 7, 8]) if srows else "")
    net = u["net"]
    col = "var(--good)" if net > 0 else ("var(--bad)" if net < 0 else "var(--text)")
    sign = "+" if net > 0 else ("−" if net < 0 else "")
    lead = (f'<p class="g-act" style="margin:0 0 10px">В '
            f'{C.month_ru(f.get("m_prev", ""), "pre")} зарплату здесь получали '
            f'<b>{C.fmt_num(u["base"])}</b> человек. За '
            f'{C.month_ru(f.get("m_cur", ""))} перестали '
            f'<b style="color:var(--bad)">{C.fmt_num(u["left"])}</b>, из них '
            f'<b>{C.fmt_num(u["gone"])}</b> не получают зарплату нигде; начали '
            f'<b style="color:var(--good)">{C.fmt_num(u["came"])}</b> — чистое '
            f'изменение <b style="color:{col}">{sign}{C.fmt_num(abs(net))}</b>.</p>')
    kinds = [("перестали получать совсем", u["gone"]),
             ("получают зарплату в другой организации", u["moved"]),
             ("получили меньше порога", u["below"]),
             ("приходят только незарплатные выплаты", u["other"])]
    krows = [[C.esc(t), C.fmt_num(v),
              f'{v / u["left"] * 100:.0f}%' if u["left"] else "—"]
             for t, v in kinds if v]
    k_tbl = C.table(["Куда делись ушедшие", "чел", "доля ушедших"], krows,
                    num_cols=[1, 2]) if krows else ""
    return (f'<div class="gd-block"><h4>Переток ФЛ — {C.esc(unit_label)} в разрезе '
            f'сегментов</h4>{lead}{k_tbl}'
            + (f'<h4 style="margin:18px 0 6px">По сегментам</h4>{seg_tbl}'
               if seg_tbl else "") + '</div>')


def _rank_by_exec(units: list) -> dict:
    """Места ТБ по прогнозному выполнению плана: tb_id -> (место, всего).

    Равные проценты получают одно место (1, 2, 2, 4) — иначе два банка с одним и
    тем же выполнением стояли бы на разных строчках рейтинга по случайности
    сортировки. Банки без выполнения в рейтинг не попадают: место «последний»
    означало бы худший результат, а не отсутствующий.
    """
    vals = [(a.tb_id, a.verdict.get("rcp", {}).get("exec")) for a in units]
    vals = [(tb, float(ex)) for tb, ex in vals if ex is not None]
    total = len(vals)
    out, place = {}, 0
    prev = None
    for i, (tb, ex) in enumerate(sorted(vals, key=lambda x: -x[1]), start=1):
        if prev is None or abs(ex - prev) > 1e-9:
            place = i
            prev = ex
        out[tb] = (place, total)
    return out


def _rank_cell(rk: tuple | None) -> str:
    """Ячейка ранга: место и через дробь — из скольких. Формат тот же, что в матрице."""
    if not rk:
        return '<span style="color:var(--text-2)">—</span>'
    return f'<span class="rk">{rk[0]}<i>/{rk[1]}</i></span>'


def _delta_cell(delta: float) -> str:
    """Отклонение от плана в КОЛОНКЕ таблицы: только знак, число и цвет.

    Единица («чел») и смысл («к плану») вынесены в шапку колонки: в таблице на
    дюжину строк подпись повторялась бы у каждого числа и мешала сравнивать
    столбец по вертикали. В тексте, где число стоит одно, работает `_delta_html`
    — там подпись нужна.
    """
    if abs(delta) < 0.5:
        return '<b style="color:var(--text-2)">0</b>'
    col = "var(--good)" if delta > 0 else "var(--bad)"
    sign = "+" if delta > 0 else "−"
    return f'<b style="color:{col}">{sign}{C.fmt_num(abs(delta))}</b>'


def _tb_portfolio_dialog(sb: analyze.Analysis, preps: list, b: bank.Bank) -> str:
    """Плашка «Портфель по всем ТБ»: прогноз, закрытый месяц и помесячная динамика.

    Отдельное окно рядом с «Управлением портфелем», потому что отвечает на вопрос
    другого масштаба: не «что с портфелем этой области», а «как выглядит сеть
    целиком». Одно на весь документ — содержимое от уровня не зависит, и держать
    по копии на каждой из тринадцати вкладок незачем.

    Три таблицы отвечают на три разных вопроса: что будет по прогнозу, что уже
    случилось в закрытом месяце и как выполнение шло месяц за месяцем. Числа —
    те же, что в плашках уровней: прогноз берётся из витрины (prediction_amt),
    факт закрытого месяца — из факта витрины, свой расчёт здесь не появляется.
    """
    if not preps:
        return ""
    d = sb.dates or {}
    units = sorted(preps, key=lambda a: analyze._ru_key(a.tb_full))

    # Ранг в таблице прогноза — НАШ порядок по прогнозному выполнению: витрина
    # ранжирует банки только по закрытому месяцу (окно rank() в METRICS_VERDICT),
    # прогнозного ранга в ней нет. Числа, по которым строится порядок, остаются
    # витринными — сортируется их же колонка «выполнение», и место в ней читатель
    # может пересчитать глазами прямо по таблице.
    fc_rank = _rank_by_exec(units)
    # Ранг закрытого месяца берётся у витрины и совпадает с рангом в плашке
    # прогноза («ранг ТБ N из M за закрытый месяц») — свой здесь не считаем.
    cl_rank = {tb: rk for tb, rk in (sb.ranks or {}).items()}

    def money_rows(src: str) -> list:
        """Строки таблицы: ранг, план, значение, отклонение и выполнение по ТБ."""
        ranks = fc_rank if src == "forecast" else cl_rank
        out = []
        for a in units + [sb]:
            v = (a.verdict if src == "forecast" else a.closed).get("rcp", {})
            plan, val = float(v.get("plan") or 0), float(v.get("fact") or 0)
            ex = v.get("exec")
            name = C.esc(a.tb_full if a is not sb else "Сбербанк — итог")
            out.append([
                (f'<b>{name}</b>' if a is sb else name),
                # у банка ранга нет — сравнивать его не с кем
                _rank_cell(None if a is sb else ranks.get(a.tb_id)),
                C.fmt_num(plan), C.fmt_num(val),
                _delta_cell(val - plan),
                C.badge(_pct(ex), C.status_of(ex)),
            ])
        return out

    fc_tbl = C.table(["Территориальный банк", "ранг", "план, чел", "прогноз, чел",
                      "отклонение от плана, чел", "выполнение"],
                     money_rows("forecast"), num_cols=[1, 2, 3, 4])
    cl_tbl = C.table(["Территориальный банк", "ранг", "план, чел", "факт, чел",
                      "отклонение от плана, чел", "выполнение"],
                     money_rows("closed"), num_cols=[1, 2, 3, 4])

    # Помесячная динамика: выполнение плана по каждому ТБ за закрытые месяцы.
    # Берём ту же историю, по которой строится раздел «Динамика за 12 месяцев»,
    # поэтому числа сходятся с графиком уровня.
    rows_id_label, cells, month_dt = [], {}, {}
    for a in units:
        tr = analyze._trend_rows(b.trend, "tb", a.tb_id)
        if not tr:
            continue
        rows_id_label.append((int(a.tb_id), a.tb_short))
        for r in tr:
            lbl = r["short"]
            # порядок столбцов — по дате, а не по порядку обхода: у части банков
            # история в витрине короче, и месяц, который встретился только у
            # последнего из них, иначе встал бы в конец таблицы
            month_dt[lbl] = r["dt"]
            # Выполнение берём у витрины — тем же числом живут плашки уровней.
            # Если витрина отдала его в процентах (на проме встречается) или не
            # отдала вовсе, считаем от плана: лучше свой расчёт, чем 9990%.
            ex = r.get("exec")
            if ex is None or not 0 < ex <= 3:
                ex = (r["fact"] / r["plan"]) if r["plan"] else None
            # Месяц прежней методики: план приравнен к факту, и выполнение в нём
            # ровно 100% у всех банков по построению. Такой столбец выглядел как
            # «сеть закрыла план везде» и прямо противоречил выполнению того же
            # месяца в таблице факта — поэтому ставим прочерк.
            if r.get("no_plan"):
                ex = None
            cells[(a.tb_id, lbl)] = (ex, r["plan"] - r["fact"])
    months = sorted(month_dt, key=lambda x: month_dt[x])
    # Месяцы, где план есть по текущей методике. Если таких нет ни одного,
    # матрицы не будет вовсе: таблица из одних прочерков на сто тридцать ячеек
    # ничего не сообщает, а объяснение, почему их нет, сообщает.
    live = [lbl for lbl in months
            if any(cells.get((u, lbl), (None, 0))[0] is not None
                   for u, _n in rows_id_label)]
    dyn = ""
    if rows_id_label and live:
        dyn = ('<div class="gd-block"><h4>Динамика выполнения плана по месяцам</h4>'
               '<p class="g-act" style="margin:0 0 10px">Выполнение плана по '
               'получателям за закрытые месяцы: строка — территориальный банк, '
               'столбец — месяц. Цвет тот же, что везде в отчёте. Ранг — место '
               'в сети по выполнению плана за закрытый месяц '
               f'{C.esc(d.get("closed_label", ""))}.</p>'
               + _method_note()
               + C.heat_matrix(rows_id_label, live, cells, unit_head="ТБ",
                               ranks=sb.ranks or None)
               + '</div>')
    elif rows_id_label and months:
        y, m, _ = queries.METRIC_SWITCH_DT.split("-")
        dyn = ('<div class="gd-block"><h4>Динамика выполнения плана по месяцам'
               '</h4><p class="g-act" style="margin:0">Помесячное выполнение '
               f'плана показывается с {C.month_ru(f"{m}.{y}", "gen")} — с '
               f'перехода на расчёт по балансу и закреплению. За более ранние '
               f'месяцы план приравнивался к факту: выполнение в них равно 100% '
               f'по построению у всех банков, и сравнивать их между собой или с '
               f'закрытым месяцем нельзя. Как менялся сам портфель, видно в '
               f'разделе «Динамика за 12 месяцев».</p></div>')

    return (
        '<dialog class="gd" id="tb-dyn"><div class="gd-sheet">'
        '<div class="gd-head"><div>'
        '<h3 style="margin:0">Портфель по территориальным банкам</h3>'
        f'<div class="gd-note">план, факт и выполнение по всей сети · '
        f'прогноз на {C.month_ru(d.get("label", ""))}, база — факт '
        f'{C.month_ru(d.get("closed_label", ""), "gen")}</div></div>'
        '<div class="gd-head-actions">'
        '<button type="button" class="gd-close" onclick="tbDynClose()" '
        'aria-label="Закрыть">×</button></div></div>'
        f'<div class="gd-block"><h4>Прогноз на {C.month_ru(d.get("label", ""))}</h4>'
        '<p class="g-act" style="margin:0 0 10px">Прогноз приходит готовым — '
        'это то же число, что стоит в плашке каждого банка. Ранг — место по '
        'прогнозному выполнению плана: готового ранга по прогнозу нет, он '
        'считается только по закрытому месяцу, поэтому здесь банки упорядочены '
        'по колонке «выполнение» этой же таблицы.</p>'
        f'{fc_tbl}</div>'
        f'<div class="gd-block"><h4>Факт '
        f'{C.month_ru(d.get("closed_label", ""), "gen")}</h4>'
        '<p class="g-act" style="margin:0 0 10px">Ранг — то же место, что стоит '
        'в плашке прогноза строкой «ранг ТБ».</p>'
        f'{cl_tbl}</div>'
        f'{dyn}'
        '</div></dialog>'
    )


# Пошаговая инструкция: один шаг на экране, список шагов сверху, «Назад»/«Далее»
