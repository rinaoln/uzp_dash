QUALITY = {key(n): q for q, names in ((PROMISED, _PROMISED), (CONFIRMED, _CONFIRMED))
           for n in names}
# Длинные ключи первыми: «Сезонный бизнес (восстановление…» должен совпасть с
# полной формулировкой раньше, чем с её началом.
_PREFIXES = sorted(QUALITY, key=len, reverse=True)


def _lookup(text: str) -> str:
    k = key(text)
    if not k:
        return ""
    if k in QUALITY:
        return QUALITY[k]
    # Сотрудник дописывает к пункту формы уточнение: «Переток в другую
    # организацию (холдинг)». Пункт считается узнанным, если ответ с него
    # начинается и дальше идёт не продолжение слова.
    for p in _PREFIXES:
        if k.startswith(p) and not k[len(p)].isalnum():
            return QUALITY[p]
    return ""


def classify(questionnaire: str | None, comment: str | None = None) -> str:
    """Категория качества отработки задачи или "" — причина не из справочника.

    Приоритет у ответа чек-листа на вопрос о причине оттока; если его нет —
    комментарий задачи, когда он целиком (или одной строкой) равен пункту
    справочника: так приходят коды вида STAFF_TURNOVER.
    """
    from .text_rules import OUTFLOW_QUESTION_HINTS, parse_questionnaire
    for question, answer in parse_questionnaire(questionnaire).items():
        if any(h in question.lower() for h in OUTFLOW_QUESTION_HINTS):
            found = _lookup(answer) or _lookup((answer or "").split("\n", 1)[0])
            if found:
                return found
    for line in [comment or ""] + str(comment or "").split("\n"):
        if key(line) in QUALITY:
            return QUALITY[key(line)]
    return ""
