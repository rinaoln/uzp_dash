# 5. Обещание возврата получателей.
#
# Раздел «Отток» делит потери на две группы, и первая из них — «обещали вернуться,
# но не вернулись». Обещание живёт в тексте задачи по оттоку, в двух видах:
#   * СТРУКТУРНО — в чек-листе есть пункты «Ожидаемый возврат получателей» и
#     «Ожидаемый месяц возврата». Это основной и самый надёжный источник;
#   * СЛОВАМИ — в свободном комментарии («сотрудники вернутся в августе»).
#
# Чек-лист сильнее комментария: там ответ выбран из формы, а не написан от руки.
# Ответы-заглушки («Пункт не актуален», «Нет», «0 чел») обещанием НЕ считаются —
# иначе в группу попали бы все, у кого в задаче просто заполнен этот пункт.
# --------------------------------------------------------------------------- #
RETURN_QTY_HINTS = ("ожидаемый возврат", "возврат получателей", "планируемый возврат",
                    "ожидаемое количество вернувшихся", "вернётся получателей",
                    "вернется получателей")
RETURN_MONTH_HINTS = ("месяц возврата", "срок возврата", "дата возврата",
                      "когда вернутся")
# Ответ без числа, но означающий «да, вернутся»
_RETURN_YES = {"да", "будет", "будут", "планируется", "ожидается", "вернутся",
               "подтверждено", "подтверждён", "подтвержден", "есть"}
_QTY_RE = re.compile(r"\d[\d\s ]*")
# Обещание в свободном тексте. Проверяется с анти-отрицанием (_has_negation):
# «сотрудники не вернутся» обещанием быть не должно.
_PROMISE_PATTERNS: tuple[str, ...] = (
    r"вернут\w*ся", r"обеща\w+ вернуть", r"планиру\w+ вернуть", r"гарантиру\w+ возврат",
    r"возврат\w*[^.]{0,20}ожида", r"ожида\w+[^.]{0,20}возврат", r"верн[ёе]м",
    r"возврат\w*[^.]{0,20}планир",
)


def any_month(text: str | None, ref: tuple[int, int] | None = None) -> str | None:
    """Самый поздний месяц, названный в тексте, как «MM.YYYY» (или None).

    В отличие от `deadline`, срок в прошлом тоже возвращается: обещание вернуть
    людей в июне, когда на дворе сентябрь, — самое интересное в группе «обещали
    вернуться, но не вернулись», и прятать его нельзя.

    `ref` = (год, месяц) отчёта: из него берётся год для месяца, названного без
    года («вернутся в августе»). Без `ref` такие упоминания пропускаем — год
    гадать нельзя, а «08.0001» в отчёте выглядел бы поломкой.
    """
    n = _norm(text)
    if not n:
        return None
    ref_pair = ref or (0, 0)
    found: list[tuple[int, int]] = []
    for m in _DMY_RE.finditer(n):
        found.append((_year_of(m.group(2), ref_pair), int(m.group(1))))
    for m in _MY_RE.finditer(n):
        found.append((_year_of(m.group(2), ref_pair), int(m.group(1))))
    for m in _MONTH_RE.finditer(n):
        num = _month_of(m.group(1))
        if num:
            found.append((_year_of(m.group(2), ref_pair), num))
    found = [(y, mo) for y, mo in found if y > 1900]
    if not found:
        return None
    y, mo = max(found)
    return f"{mo:02d}.{y}"


# Ответы, которыми пункт чек-листа закрывают «ничего не жду»
_RETURN_NO = {"нет", "не будет", "не планируется", "не ожидается", "0", "0 чел"}


def promised_return(questionnaire: str | None, comment: str | None = None,
                    ref: tuple[int, int] | None = None) -> dict | None:
    """Обещание вернуть получателей из текста задачи по оттоку.

    Возвращает {"qty": int|None, "month": "MM.YYYY"|"", "source": …} или None.
    `qty=None` означает обещание без числа («Ожидаемый возврат — да»).

    Заглушки чек-листа здесь разбираются ОТДЕЛЬНО от общего списка STOP_TEMPLATES:
    «да» и «нет» в нём помечены как односложные и неинформативные — и это верно для
    свободного комментария, но в пункте «Ожидаемый возврат получателей» ровно они и
    есть ответ.
    """
    qty, month, src = None, "", ""
    for question, answer in parse_questionnaire(questionnaire).items():
        ql = question.lower()
        ans = _norm(answer)
        if not ans:
            continue
        if any(h in ql for h in RETURN_QTY_HINTS):
            if ans in _RETURN_NO or ans in ("пункт не актуален", "не актуально", "-", "—"):
                continue
            m = _QTY_RE.search(ans)
            if m:
                n = int(re.sub(r"\D", "", m.group(0)) or 0)
                if n > 0:
                    qty, src = n, "чек-лист задачи"
            elif ans in _RETURN_YES:
                src = src or "чек-лист задачи"
        elif any(h in ql for h in RETURN_MONTH_HINTS):
            if ans in STOP_TEMPLATES:
                continue
            month = any_month(answer, ref) or answer.strip()[:16]
    if src:
        # месяц из чек-листа может стоять в другом пункте, а может и вовсе
        # отсутствовать — тогда пробуем вытащить его из комментария
        return {"qty": qty, "month": month or (any_month(comment, ref) or ""),
                "source": src}
    n = _norm(comment)
    if n:
        for pat in _PROMISE_PATTERNS:
            m = re.search(pat, n)
            if m and not _has_negation(n, m.start()):
                return {"qty": None, "month": any_month(comment, ref) or "",
                        "source": "комментарий сотрудника"}
    return None


