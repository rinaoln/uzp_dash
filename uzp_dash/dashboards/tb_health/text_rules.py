# 6. Короткая причина ухода — для свода по причинам в разделе «Отток».
#
# `outflow_reason` выше отвечает на другой вопрос — «есть ли смысл идти к клиенту»,
# и её формулировки несут вердикт («Сокращение штата у клиента — влиять нечем»).
# Для свода нужен ЯРЛЫК, по которому строки группируются, поэтому причина берётся
# так, как её выбрал сотрудник в чек-листе, а вердикт из неё отрезается.
# --------------------------------------------------------------------------- #
# Ключевые слова и чек-лист называют одно и то же разными словами. Сводим только
# очевидные пары — там, где это буквально одна причина, а не похожие.
REASON_SYNONYMS = {
    "ушли в другой банк": "Смена зарплатного банка",
    "сокращение штата у клиента": "Сокращение штата",
}

# Какие находки по ключевым словам ВООБЩЕ являются причиной ухода.
#
# KEYWORD_RULES отвечают на более широкий вопрос — «что происходит с клиентом», — и
# половина их формулировок описывает ход переговоров о привлечении: «нужна встреча
# с ЛПР», «возражение бухгалтерии», «получено согласие». В своде «из-за чего уходят»
# такие строки выглядели бы причинами оттока, хотя объясняют совсем другое. Поэтому
# из комментария причиной признаётся только то, что названо здесь; ответ чек-листа
# в этот список не входит — там вопрос прямо про причину оттока.
OUTFLOW_CAUSE_LABELS = {
    "Смена зарплатного банка",
    "Текучка персонала",
    "Сокращение штата",
    "Сезонный фактор",
    "Признаки ликвидации/банкротства",
}


def outflow_reason_label(questionnaire: str | None,
                         comment: str | None = None) -> tuple[str, str]:
    """Короткая причина ухода и её источник: (причина, источник).

    Приоритет у чек-листа: там причина выбрана из формы, а не написана от руки.
    Пустая строка означает, что причина в задаче не зафиксирована, — гадать по
    косвенным признакам в отчёте, который читает правление, нельзя.
    """
    for question, answer in parse_questionnaire(questionnaire).items():
        if not any(h in question.lower() for h in OUTFLOW_QUESTION_HINTS):
            continue
        ans = (answer or "").strip()
        if not ans or _norm(ans) in STOP_TEMPLATES:
            continue
        return _reason_label(ans), "чек-лист задачи"
    m = match_keyword(comment)
    if m:
        label = _reason_label(m["reason"])
        if label in OUTFLOW_CAUSE_LABELS:
            return label, "комментарий сотрудника"
    return "", ""


def _reason_label(text: str) -> str:
    """Ярлык причины: без вердикта после тире, с заглавной буквы, не длиннее строки."""
    label = str(text).split(" — ")[0].strip().strip(".")
    label = REASON_SYNONYMS.get(label.lower(), label)
    return (label[:1].upper() + label[1:])[:60]


def themes(texts: list[str]) -> str:
    """Частые причины по набору текстов (для нарратива) — на тех же правилах."""
    counts: dict[str, int] = {}
    for t in texts:
        m = match_keyword(t)
        if m:
            counts[m["reason"]] = counts.get(m["reason"], 0) + 1
    if not counts:
        return "—"
    top = sorted(counts.items(), key=lambda x: -x[1])[:4]
    return ", ".join(f"{name} ({n})" for name, n in top)
