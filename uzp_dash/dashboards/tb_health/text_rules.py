"""Детерминированная обработка свободного текста воронки.

Здесь ВСЕ правила собраны явно, чтобы их можно было глазами проверить и дополнить:
  * STOP_TEMPLATES        — шаблонные/системные ответы, которые НЕ отправляем в LLM
  * OUTFLOW_REASON_RULES  — причина оттока из ЧЕК-ЛИСТА (задачи типа «Отток»)
  * KEYWORD_RULES         — частые формулировки -> причина/действие без LLM

Идея: чем больше решается здесь, тем меньше строк уходит в LLM.
"""
from __future__ import annotations

import re

# --------------------------------------------------------------------------- #
# 1. Шаблонные ответы. Ключ — нормализованный текст (lower, без пунктуации по краям).
#    Значение — пояснение, ПОЧЕМУ это шаблон (видно в логах при show_llm).
# --------------------------------------------------------------------------- #
