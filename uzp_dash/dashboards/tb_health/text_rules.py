# 4. Названный в тексте СРОК («зачисления пройдут 08.2026», «выйдут в августе»).
#
# Зачем: сотрудник может честно отработать задачу и назвать срок, который ещё не
# наступил. Требовать «проконтролируйте» в июле по сроку на август — некорректно,
# это не недоработка, а нормальный ход работы. Сравниваем найденный срок с ОПОРНЫМ
# месяцем дэша: интересует только срок В БУДУЩЕМ.
# --------------------------------------------------------------------------- #
# Стем месяца -> номер. Порядок важен: «март» проверяется раньше «ма[йея]».
_MONTH_STEMS: tuple[tuple[str, int], ...] = (
    ("январ", 1), ("феврал", 2), ("март", 3), ("апрел", 4), ("ма[йея]", 5),
    ("июн", 6), ("июл", 7), ("август", 8), ("сентябр", 9), ("октябр", 10),
    ("ноябр", 11), ("декабр", 12),
)
_MONTH_RE = re.compile(
    r"\b(" + "|".join(s for s, _ in _MONTH_STEMS) + r")\w*(?:\s+(\d{4})\s*г?)?")
# 15.08.2026 / 15-08-26 — сначала полная дата, чтобы не спутать день с месяцем
_DMY_RE = re.compile(r"\b\d{1,2}[.\-/](0?[1-9]|1[0-2])[.\-/](\d{2,4})\b")
# 08.2026 / 8/2026
_MY_RE = re.compile(r"\b(0?[1-9]|1[0-2])[.\-/](\d{4})\b")
# «в 3 квартале», «до конца 4 кв.»
_Q_RE = re.compile(r"\b([1-4])\s*(?:-?\w{0,2})?\s*(?:квартал|кв\b)")


def _month_of(match_text: str) -> int | None:
    for stem, num in _MONTH_STEMS:
        if re.match(r"^" + stem, match_text):
            return num
    return None


def _year_of(raw: str | None, ref: tuple[int, int]) -> int:
    """Год из текста; если не указан — опорный. Двузначный разворачиваем в 20xx."""
    if not raw:
        return ref[0]
    y = int(raw)
    return y + 2000 if y < 100 else y


def deadline(text: str | None, ref: tuple[int, int]) -> str | None:
    """Самый поздний срок из текста, если он ПОЗЖЕ опорного месяца ref=(год, месяц).

    Возвращает «MM.YYYY» либо None. Прошедшие сроки не возвращаем — по ним как раз
    и надо спрашивать результат, это не повод откладывать.

    Месяц без года трактуем как ОПОРНЫЙ год (не переносим в следующий): «в феврале»
    при опорном июле — это прошедший февраль, а не февраль через 7 месяцев.
    """
    n = _norm(text)
    if not n:
        return None
    found: list[tuple[int, int]] = []
    for m in _DMY_RE.finditer(n):
        found.append((_year_of(m.group(2), ref), int(m.group(1))))
    for m in _MY_RE.finditer(n):
        found.append((_year_of(m.group(2), ref), int(m.group(1))))
    for m in _MONTH_RE.finditer(n):
        num = _month_of(m.group(1))
        if num:
            found.append((_year_of(m.group(2), ref), num))
    for m in _Q_RE.finditer(n):
        found.append((ref[0], int(m.group(1)) * 3))
    future = [ym for ym in found if ym > ref]
    if not future:
        return None
    y, mo = max(future)
    return f"{mo:02d}.{y}"


