# Отрицания слева от совпадения: подтверждением НЕ считаем.
_NEG_CUES: tuple[str, ...] = (
    "не ", "нет ", "без ", "не подтвержд", "не планир", "не намерен",
    "отсутств", "риск ", "во избежан", "не требует", "не актуал", "маловероят",
)
_NEG_WINDOW = 26   # сколько символов слева осматриваем на отрицание


def _has_negation(norm_text: str, start: int) -> bool:
    """Есть ли отрицание в окне слева от совпадения (start — индекс в norm_text)."""
    window = norm_text[max(0, start - _NEG_WINDOW):start]
    return any(cue in window for cue in _NEG_CUES)


def match_keyword(text: str | None) -> dict | None:
    """Первое сработавшее правило по ключевым словам (regex + анти-отрицание) или None."""
    n = _norm(text)
    if not n:
        return None
    for patterns, reason, action, verdict, needs_llm in KEYWORD_RULES:
        for pat in patterns:
            m = re.search(pat, n)
            if m and not _has_negation(n, m.start()):
                return {"reason": reason, "action": action, "verdict": verdict,
                        "source": "ключевые слова", "needs_llm": needs_llm}
    return None


