def _outflow_facts(a, al, unit: str) -> str:
    """Факты раздела «Отток» для промпта — агрегаты плюс несколько крупнейших потерь.

    Имена организаций и подразделений уходят в модель только псевдонимами: раздел
    называет поимённо тех, у кого уже случилась потеря, и это ровно тот случай, когда
    настоящее имя за пределы контура уходить не должно.
    """
    o = getattr(a, "outflow", {}) or {}
    if not o:
        return "Отток: за окно потерь не зафиксировано."
    def _what(r):
        p = r.get("promise") or {}
        why = f'; причина: {r["out_reason"]}' if r.get("out_reason") else ""
        if r.get("promise_broken"):
            qty = f'{p["qty"]:.0f} чел' if p.get("qty") else "возврат"
            when = f', срок {p["month"]}' if p.get("month") else ""
            return f"обещали вернуть {qty}{when} — не вернулись{why}"
        if r["tasks"]:
            return f"отработали, возврата нет{why}"
        return f"месяц ухода вне окна задач{why}"

    top = "; ".join(
        f'{al.alias("Организация", r["name"])} [{al.alias(unit, r["unit"])}] '
        f'−{r["kept"]:.0f} чел, {_what(r)}'
        for r in o["rows"][:5])
    # Счётчик организаций без задач в модель НЕ уходит: в отчёте эта цифра не
    # показывается, а всё, что попадает в промпт, рано или поздно всплывает в тексте.
    # Раздел делится на две группы, и модели достаточно знать их состав и вес.
    return (
        f"Отток за три закрытых месяца: ушли {o['tot_gone']:.0f} чел из "
        f"{o['n_all']} организаций, вернулись {o['tot_ret']:.0f}, "
        f"потеряны окончательно {o['tot_kept']:.0f}.\n"
        f"Раздел разделён на две группы клиентов. Первая — обещали вернуться, но "
        f"не вернулись: договорённость о возврате зафиксирована в задаче по оттоку, "
        f"возврата нет ({o['n_promised']} орг, {o['kept_promised']:.0f} чел). "
        f"Вторая — отработали, но без результата: работа велась, обещаний не было, "
        f"не вернулся никто ({o['n_worked']} орг, {o['kept_worked']:.0f} чел).\n"
        + _outflow_reasons_line(o)
        + f"Крупнейшие потери: {top}."
    )


def _outflow_reasons_line(o: dict) -> str:
    """Свод по причинам ухода для промпта — с обязательной оговоркой о покрытии.

    Без неё модель пишет «главная причина оттока — смена банка», хотя причина
    известна у части организаций, и доля считается только от них.
    """
    rows = o.get("reasons") or []
    if not rows:
        return ""
    cov = (float(o.get("reason_known_kept") or 0) / o["tot_kept"] * 100
           if o.get("tot_kept") else 0)
    top = "; ".join(f"{g['reason']} — {g['kept']:.0f} чел у {g['n']} орг "
                    f"({g['share'] * 100:.0f}%)" for g in rows[:4])
    return (f"Причины ухода (зафиксированы у {o.get('reason_known_n', 0)} из "
            f"{o['n_all']} организаций, это {cov:.0f}% потерь; доли — от этой "
            f"части): {top}.\n")


