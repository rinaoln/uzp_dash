def _norm(name) -> str:
    """К верхнему регистру, с одиночными пробелами."""
    return " ".join(str(name or "").split()).upper()


def is_person_name(name, strict: bool = False) -> bool:
    """Название организации — это имя человека?

    `strict` — режим для ММБ: там под правило попадает и «Фамилия Имя» без
    отчества и без узнаваемого имени — два-три русских слова без признаков
    вывески, из которых хотя бы одно похоже на фамилию.

    Одно слово («ДУДЬЕВ», «СТРОЙИНВЕСТ») не маскируется ни в каком режиме:
    отличить фамилию от торгового названия по одному слову нельзя, а ФИО
    физического лица из одного слова не состоит.

    ЧТО ПРАВИЛО НЕ ЛОВИТ: фамилию с редким окончанием рядом с именем, которого
    нет в списке — «ЦОЙ ЛИ». Такие останутся с названием.
    """
    s = _norm(name)
    if not s:
        return False
    if _ENTREPRENEUR.search(s):
        return True
    words = _WORDS_RE.findall(s)
    if any(w in _ORG_WORDS for w in words):
        return False
    if any(rx.search(s) for rx in _PERSON):
        return True
    if 2 <= len(words) <= 3 and any(w in _GIVEN for w in words):
        return True
    if strict and 2 <= len(words) <= 3 and _ALPHA_ONLY.match(s):
        # ни цифр, ни кавычек, ни латиницы, ни точек; каждое слово длиннее двух
        # букв, и хотя бы одно похоже на фамилию
        return (all(len(w) >= 3 for w in words)
                and any(_looks_surname(w) for w in words))
    return False


def org_label(name, inn, strict: bool = False) -> str:
    """Как называть организацию в отчёте: имя — или номер вместо имени человека."""
    s = str(name or "").strip()
    if not s or is_person_name(s, strict):
        return f"Орг. {inn}" if inn not in (None, "") else ""
    return s


def mask_people(df, name_col: str = "company_name", inn_col: str = "inn",
                seg_col: str | None = None,
                strict_segs: tuple[str, ...] = STRICT_SEGMENTS):
    """Заменить имена людей на номер организации во всей колонке кадра.

    `seg_col` — колонка с КОРОТКИМ кодом сегмента («ММБ», «КСБ», …). Если она
    передана, строки сегментов из `strict_segs` проходят строгую проверку.

    Возвращает (кадр, сколько заменено всего, сколько из них только по строгому
    правилу) — числа печатаются в лог сборки: молча прятать часть названий
    нельзя, иначе однажды окажется, что правило съело обычные компании.
    """
    if df is None or getattr(df, "empty", True) or name_col not in df:
        return df, 0, 0
    names = df[name_col].astype(str)
    inns = df[inn_col] if inn_col in df else [""] * len(df)
    segs = df[seg_col] if (seg_col and seg_col in df) else [None] * len(df)
    masked, n, n_strict = [], 0, 0
    for nm, inn, sg in zip(names, inns, segs):
        strict = str(sg) in strict_segs
        lbl = org_label(nm, inn, strict)
        if lbl != nm.strip():
            n += 1
            if strict and not is_person_name(nm, False):
                n_strict += 1
        masked.append(lbl)
    df = df.copy()
    df[name_col] = masked
    return df, n, n_strict
